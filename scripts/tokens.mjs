// ── The tokens' hash, for the Figma mirror ─────────────────────────────────

// JSON with keys sorted at every level and no whitespace, so the same tokens
// give the same text however the file is formatted.
export function canonicalJson(v) {
  if (Array.isArray(v)) return `[${v.map(canonicalJson).join(',')}]`
  if (v && typeof v === 'object') {
    return `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${canonicalJson(v[k])}`).join(',')}}`
  }
  return JSON.stringify(v)
}

const sha256 = (text) => createHash('sha256').update(text).digest('hex')

// The hash of every file the token set is read from: one file's canonical
// JSON, or, for a resolver document, the document and each file it names.
function tokensHash(root, files) {
  if (files.length === 1) return sha256(canonicalJson(readJson(join(root, files[0]))))
  return sha256(canonicalJson(files.map((f) => [f, readJson(join(root, f))])))
}

// Whether figma/mirror.json was recorded from the tokens as they are now. A
// mirror made before 0.2.0 hashed the file's bytes, which still counts.
function figmaMirror(root, projectDir, config, files) {
  const path = join(projectDir, 'figma', 'mirror.json')
  if (!existsSync(path)) return null
  const mirror = readJson(path)
  if (typeof mirror?.tokensHash !== 'string') return null
  const source = join(root, config.tokens.source)
  const current = mirror.tokensHash === tokensHash(root, files) || mirror.tokensHash === sha256(readFileSync(source))
  return { current, syncedAt: mirror.syncedAt ?? 'an unknown date' }
}

// Record what the Figma file holds as the mirror, or report how it drifted
// since. The export is the JSON skills/figma/read-library.js returns.
function figmaCommand({ root, config, projectDir, flags, shown, tokens }) {
  const record = typeof flags.record === 'string' ? flags.record : null
  const drift = typeof flags.drift === 'string' ? flags.drift : null
  const pairsOnly = typeof flags.pairs === 'string' ? flags.pairs : null
  if ([record, drift, pairsOnly].filter(Boolean).length !== 1) fail('usage: tokens.mjs figma --pairs <export.json> | --record <export.json> [--file-key <key>] | --drift <export.json>', 2)
  const exportPath = resolve(record ?? drift ?? pairsOnly)
  if (!existsSync(exportPath)) fail(`no export at ${exportPath}; save what read-library.js returns there first`)
  const exported = readJson(exportPath)
  const { files } = buildOutputs(root, projectDir, config, tokens)
  const wanted = JSON.parse(files.find((f) => f.path.endsWith('figma-variables.json')).text)
  const mirrorPath = join(projectDir, 'figma', 'mirror.json')
  // Read only: which Figma variables pair with which tokens, and what differs,
  // before anything is written to Figma. The mirror is left as it was.
  if (pairsOnly) {
    const previous = readJson(mirrorPath, {}) ?? {}
    const fileKey = typeof flags['file-key'] === 'string' ? flags['file-key'] : undefined
    const { mirror, mismatches, notes } = recordMirror(wanted, exported, { fileKey, date: today(), previous })
    for (const n of notes) process.stderr.write(`  note: ${n}\n`)
    for (const m of mismatches) process.stderr.write(`  differs: ${m}\n`)
    const by = (match) => Object.values(mirror.variables).filter((v) => (v.match ?? 'name') === match).length
    const total = Object.keys(mirror.variables).length
    const wantedCount = (wanted.collections ?? []).reduce((n, c) => n + (c.variables?.length ?? 0), 0)
    process.stdout.write(`massimo tokens figma: ${total} of ${wantedCount} variables pair with the file (${by('name')} by name, ${by('id')} by id, ${by('code')} by code syntax), ${mismatches.length} ${mismatches.length === 1 ? 'difference' : 'differences'}; nothing written\n`)
    return
  }
  if (record) {
    const previous = readJson(mirrorPath, {}) ?? {}
    const fileKey = typeof flags['file-key'] === 'string' ? flags['file-key'] : undefined
    const { mirror, mismatches, notes } = recordMirror(wanted, exported, { fileKey, tokensHash: tokensHash(root, tokens.files), date: today(), previous })
    writeText(mirrorPath, jsonText(mirror))
    for (const n of notes) process.stderr.write(`  note: ${n}\n`)
    for (const m of mismatches) process.stderr.write(`  mismatch: ${m}\n`)
    const count = Object.keys(mirror.variables).length
    process.stdout.write(`massimo tokens figma: recorded ${count} variables, ${Object.keys(mirror.textStyles).length} text styles and ${Object.keys(mirror.effectStyles).length} effect styles in ${shown(mirrorPath)}${mirror.modes === 'default only' ? '; the file allows one mode per collection, so only the default mode is mirrored' : ''}; ${mismatches.length} ${mismatches.length === 1 ? 'mismatch' : 'mismatches'} with code\n`)
    if (mismatches.length > 0) process.exit(1)
    return
  }
  if (!existsSync(mirrorPath)) fail(`no ${shown(mirrorPath)} yet; record the mirror first with --record`)
  const { markdown, total } = driftReport(wanted, readJson(mirrorPath), exported, { date: today() })
  const out = join(projectDir, 'figma', 'drift.md')
  writeText(out, markdown)
  process.stdout.write(`massimo tokens figma: ${total} ${total === 1 ? 'difference' : 'differences'} since the mirror; wrote ${shown(out)}\n`)
}

const warnAll = (model) => {
  for (const p of model.problems.filter((x) => x.level === 'warning')) process.stderr.write(`massimo: warn: ${p.path}: ${p.message}\n`)
}

// ── Orchestration ───────────────────────────────────────────────────────────

// Every file `build` writes, as { path (absolute), text }. Throws on a bad token set.
function buildOutputs(root, projectDir, config, tokens) {
  const model = modelOf(tokens, config)
  const out = []
  for (const output of config.tokens.outputs ?? []) {
    if (!FORMATS.includes(output.format)) {
      throw new Error(`tokens.outputs: unknown format "${output.format}". Use one of: ${FORMATS.join(', ')}.`)
    }
    const text = {
      css: () => buildCss(model, config),
      tailwind4: () => buildTailwind4(model),
      tailwind3: () => buildTailwind3(model),
      scss: () => buildScss(model),
      json: () => buildJson(model),
      ts: () => buildTs(model),
      designmd: () => buildDesignMd(model, config, root, projectDir),
    }[output.format]()
    out.push({ path: join(root, output.path), text })
  }
  out.push({ path: join(projectDir, 'tokens', 'figma-variables.json'), text: buildFigma(model) })
  out.push({ path: join(projectDir, 'kit', 'kit.css'), text: buildKit(model, tokens.origin, tokens.files, config) })
  return { model, files: out }
}

// ── Migration between the two dialects ─────────────────────────────────────

// Outputs as text with their "Generated by" lines left out, to compare two builds.
const bodyOf = (text) => text.split('\n').filter((l) => !l.includes('Generated by massimo') && !l.startsWith('/* Source: ')).join('\n')

function migrationReport({ from, to, direction, losses, changed }) {
  const lines = ['# Token migration', '', `${today()} · ${from} to ${to} (${direction}).`, '', '## What did not carry over exactly', '']
  if (losses.length === 0) lines.push('Every value carried over exactly.')
  for (const l of losses) lines.push(`- \`${l.token}\` (${l.kind}): ${l.detail}`)
  lines.push('', '## Outputs', '')
  if (changed.length === 0) lines.push('Every output builds the same as before, apart from the line that names its source. Run the build to refresh that line.')
  else for (const c of changed) lines.push(`- \`${c}\` builds differently; review it before committing.`)
  return `${lines.join('\n')}\n`
}

// Convert the token source to 2025.10 (or back with --to legacy), write a
// report of anything that did not carry over exactly, check every output
// still builds the same, and point the config at the new source.
function migrate({ root, config, projectDir, configPath, flags, shown }) {
  const to = flags.to === undefined || flags.to === true ? '2025.10' : String(flags.to)
  if (!['2025.10', 'legacy'].includes(to)) fail('--to takes 2025.10 or legacy', 2)
  const loaded = loadTokens(root, config)
  if (!loaded) fail(`no token source at ${config.tokens.source}`)
  const vendored = vendoredVersion(projectDir)
  if (vendoredOlder(vendored)) {
    fail(`the scripts in ${shown(join(projectDir, 'scripts'))} are ${vendored}, older than this ${SCRIPTS_VERSION}; update them first (init.mjs --update-scripts), or CI and teammates on ${vendored} cannot read the new files`)
  }
  const dir = dirname(join(root, config.tokens.source))
  const before = buildOutputs(root, projectDir, config, loaded)
  let files
  let losses
  let source
  if (to === '2025.10') {
    if (loaded.format !== 'legacy') fail(`${config.tokens.source} is already in the 2025.10 format`)
    const converted = typedFromLegacy(before.model.tokens, before.model.typeOf)
    losses = converted.losses
    files = writeTokenSet({ tokens: converted.tokens, defaultMode: before.model.defaultMode, name: 'Design tokens' })
    source = 'tokens.resolver.json'
  } else {
    if (loaded.format !== '2025.10') fail(`${config.tokens.source} is already in the dialect before 0.2.0`)
    const m = before.model
    const asVar = (alias) => `var(${m.byName.get(aliasPath(alias))?.cssVar ?? alias})`
    const legacy = writeLegacy(m.tokens.map((t) => ({ ...t, type: m.typeOf(t) })), (type, v) => cssText(type, v, asVar))
    losses = legacy.losses
    for (const t of m.tokens) {
      if ([...nestedRefs(t.value)].length > 0) losses.push({ token: t.name, kind: 'changed', detail: 'a composite with references became CSS text; the references inside became var()' })
    }
    files = { 'tokens.json': tokenJson(legacy.doc) }
    source = 'tokens.json'
  }
  const targets = Object.entries(files).map(([name, text]) => [join(dir, name), text])
  const taken = targets.filter(([p]) => existsSync(p) && p !== join(root, config.tokens.source))
  if (taken.length > 0 && !truthy(flags.force)) fail(`these files exist already: ${taken.map(([p]) => shown(p)).join(', ')}. Move them, or pass --force to overwrite them.`)
  for (const [p, text] of targets) writeText(p, text)
  const newSource = rel(root, join(dir, source))
  const nextConfig = { ...config, tokens: { ...config.tokens, source: newSource } }
  const after = buildOutputs(root, projectDir, nextConfig, loadTokens(root, nextConfig))
  const changed = after.files.filter((f, i) => bodyOf(f.text) !== bodyOf(before.files[i]?.text ?? '')).map((f) => shown(f.path))
  const reportPath = join(dir, 'migration-report.md')
  writeText(reportPath, migrationReport({ from: config.tokens.source, to: newSource, direction: to === '2025.10' ? 'to the W3C Design Tokens format 2025.10' : 'back to the dialect massimo wrote before 0.2.0', losses, changed }))
  if (existsSync(configPath)) {
    const raw = readJson(configPath, {})
    raw.tokens = { ...(raw.tokens ?? {}), source: newSource }
    writeText(configPath, jsonText(raw))
  }
  process.stdout.write(
    `massimo tokens migrate: wrote ${targets.map(([p]) => shown(p)).join(', ')} and ${shown(reportPath)}; ${losses.length} ${losses.length === 1 ? 'value' : 'values'} not carried over exactly, ${changed.length} ${changed.length === 1 ? 'output' : 'outputs'} changed. ${existsSync(configPath) ? `massimo.config.json now reads ${newSource}.` : `Set tokens.source to ${newSource} in massimo.config.json.`} Then run: ${scriptCommand(root, projectDir, 'tokens', 'build')}\n`,
  )
}

// ── The mirror: the style files as the token set ───────────────────────────

const IMPORTANT = /\s*!important$/i

// The style files the config names, with their text.
const styleSheets = (root, config) => expandGlobs(root, config.tokens.styleFiles, [], config.ignore).map((file) => ({ file, css: readFileSync(join(root, file), 'utf8') }))

// Where the mirror lives: the folder of tokens.source, which names its
// resolver document.
function mirrorDir(root, config) {
  const source = config.tokens.source
  if (!source.endsWith('.resolver.json')) throw new Error(`the mirror is a resolver document, and tokens.source is ${source}; point it at a .resolver.json file, or leave it unset`)
  return dirname(join(root, source))
}

// The token set the style files make, as the files writeTokenSet writes by
// path in the mirror's folder, with notes on what is not kept as written.
// A property with a value on the root is a token; its themes come from the
// config's selectors, its values under any other selector go to
// `$extensions.massimo.scopes`, and the comment before it is its
// description. A property set only in a theme or inside scopes has no
// default to give a token, so the base file keeps it by name with its values.
function mirrorSet(root, config, projectDir) {
  const sheets = styleSheets(root, config)
  if (sheets.length === 0) throw new Error(`tokens.styleFiles names no file to mirror (${config.tokens.styleFiles.join(', ') || 'it is empty'})`)
  const { declarations: found } = sheetDeclarations(sheets, config)
  const notes = []
  const props = new Map()
  let tailwind = 0
  for (const d of found) {
    if (d.name.startsWith('--tw-')) {
      tailwind++
      continue
    }
    const p = props.get(d.name) ?? { modes: {}, scopes: {}, all: {}, comment: '', rootComment: '' }
    const value = d.value.replace(IMPORTANT, '')
    if (value !== d.value) notes.push(`${d.name} under ${d.key} is !important, which a token cannot hold; the mirror keeps the value without it`)
    if (d.mode === 'default') p.default = value
    else if (d.mode) p.modes[d.mode] = value
    else p.scopes[d.key] = value
    p.all[d.key] = value
    if (!p.comment && d.comment) p.comment = d.comment
    if (d.mode === 'default' && !p.rootComment && d.comment) p.rootComment = d.comment
    props.set(d.name, p)
  }
  if (tailwind > 0) notes.push(`${tailwind} declarations of Tailwind's own --tw-* properties are not mirrored`)
  const { looksLikeTheme } = themePlacer(config)
  const flagged = new Set()
  for (const d of found) {
    const mode = d.mode ? null : looksLikeTheme(d.member, d.conditions)
    if (!mode || flagged.has(d.key)) continue
    flagged.add(d.key)
    notes.push(`${d.key} looks like the ${mode === 'default' ? 'default' : mode} theme, but tokens.darkSelector and tokens.selectors do not name it, so its values are kept as a scope`)
  }
  const scoped = {}
  for (const [name, p] of props) {
    if (p.default === undefined) scoped[name] = { ...(p.comment ? { description: p.comment } : {}), scopes: p.all }
  }
  // The root and theme values, read by readCss as extract reads them.
  const byFile = new Map()
  for (const d of found) {
    if (!d.mode || props.get(d.name)?.default === undefined) continue
    byFile.set(d.file, [...(byFile.get(d.file) ?? []), { name: d.name, value: d.value.replace(IMPORTANT, ''), mode: d.mode, scope: d.mode === 'default' ? 'root' : 'selector', selector: d.key }])
  }
  const read = readCss(root, sheets.map((s) => s.file), (css, file) => byFile.get(file) ?? [])
  notes.push(...read.notes)
  for (const t of read.tokens) t.description = props.get(t.cssVar).rootComment || props.get(t.cssVar).comment
  const { tokens, losses, defaultMode } = draftFrom(read.tokens, config)
  for (const l of losses) notes.push(`${l.token} (${l.kind}): ${l.detail}`)
  // Every value the CSS output would write differently (a family's quotes,
  // a number's form) keeps the text the author wrote, so the mirror builds
  // back to the same declarations.
  const model = buildModel(tokens, config, [], { defaultMode })
  for (const t of tokens) {
    const p = props.get(t.cssVar)
    if (!t.cssOnly) {
      for (const mode of ['default', ...Object.keys(t.modes)]) {
        const want = mode === 'default' ? p.default : p.modes[mode]
        if (want === undefined || declarations(model, t, mode, true)[0][1] === want) continue
        if (mode === 'default') t.css = want
        else t.cssModes = { ...t.cssModes, [mode]: want }
      }
    }
    if (Object.keys(p.scopes).length > 0) t.scopes = p.scopes
  }
  buildModel(tokens, config, [], { defaultMode })
  const from = sheets.map((s) => s.file)
  const files = writeTokenSet({
    tokens,
    defaultMode,
    name: 'Design tokens',
    description: `A mirror of the custom properties in ${from.join(', ')}, written by massimo tokens mirror. Do not edit it by hand: change the CSS, then run ${scriptCommand(root, projectDir, 'tokens', 'mirror')}.`,
    mirror: { from, ...(Object.keys(scoped).length > 0 ? { scoped } : {}) },
  })
  const resolverName = basename(config.tokens.source)
  const named = Object.fromEntries(Object.entries(files).map(([path, text]) => [path === 'tokens.resolver.json' ? resolverName : path, text]))
  return { files: named, notes, from, count: tokens.length, withScopes: tokens.filter((t) => t.scopes).length, scoped: Object.keys(scoped).length }
}

// Whether the mirror may write where it would: never over a token set that
// is not a mirror, or one a newer massimo wrote.
function guardMirror(dir, resolverName, shown) {
  const base = join(dir, 'base.tokens.json')
  const doc = existsSync(base) ? readJson(base) : null
  const format = doc ? formatOf(doc) : null
  if (format !== null && format > FORMAT_VERSION) fail(`${shown(base)} was written by a newer massimo (format ${format}; this one reads ${FORMAT_VERSION}). Update massimo.`)
  if (doc ? !doc.$extensions?.massimo?.mirror : existsSync(join(dir, resolverName))) {
    fail(`${shown(doc ? base : join(dir, resolverName))} holds a token set that is not a mirror of the style files, and the mirror never writes over one. Move it, or turn tokens.mirror off.`)
  }
}

// The mirror files as they should be, and which of them are not.
function mirrorState(root, config, projectDir) {
  const dir = mirrorDir(root, config)
  const set = mirrorSet(root, config, projectDir)
  const files = Object.entries(set.files).map(([name, text]) => ({ path: join(dir, name), text }))
  return { ...set, dir, files, stale: files.filter((f) => !existsSync(f.path) || readFileSync(f.path, 'utf8') !== f.text) }
}

// Outputs that would write over a style file the mirror reads as the source.
const overSources = (root, config) => {
  if (!config.tokens.mirror) return []
  const sources = new Set(expandGlobs(root, config.tokens.styleFiles, [], config.ignore))
  return (config.tokens.outputs ?? []).filter((o) => sources.has(rel(root, join(root, o.path))))
}

function mirrorCommand({ root, config, projectDir, flags, shown }) {
  if (!config.tokens.mirror) fail('tokens.mirror is off. Set it to true in massimo.config.json first: the style files then stay the source, and the token set becomes their checked mirror.')
  const state = mirrorState(root, config, projectDir)
  guardMirror(state.dir, basename(config.tokens.source), shown)
  if (truthy(flags.check)) {
    for (const f of state.stale) process.stderr.write(`  stale: ${shown(f.path)}${existsSync(f.path) ? '' : ' (missing)'}\n`)
    if (state.stale.length > 0) {
      process.stdout.write(`massimo tokens mirror: behind the style files (${state.stale.length} of ${state.files.length} files). Run: ${scriptCommand(root, projectDir, 'tokens', 'mirror')}\n`)
      process.exit(1)
    }
    process.stdout.write(`massimo tokens mirror: up to date with ${state.from.join(', ')} (${state.count} tokens)\n`)
    return
  }
  for (const f of state.files) writeText(f.path, f.text)
  for (const n of state.notes) process.stderr.write(`  note: ${n}\n`)
  process.stdout.write(`massimo tokens mirror: ${state.count} tokens from ${state.from.join(', ')}, ${state.withScopes} with values in scopes, ${state.scoped} set only in themes or scopes; wrote ${state.files.map((f) => shown(f.path)).join(', ')}\n`)
}

const BOOLEAN_FLAGS = new Set(['strict', 'force'])

function main() {
  const argv = process.argv.slice(2).map((a) => (a.startsWith('--') && BOOLEAN_FLAGS.has(a.slice(2)) ? `${a}=true` : a))
  const { _: positionals, flags } = parseArgs(argv)
  const mode = positionals[0]
  const MODES = ['extract', 'build', 'kit', 'check', 'preview', 'hash', 'migrate', 'figma', 'mirror']
  if (!MODES.includes(mode)) fail(`usage: tokens.mjs <${MODES.join('|')}> [--strict]`, 2)
  const { root, config, projectDir, configPath } = loadConfig(flags)
  warnIfVendoredOlder(projectDir, import.meta.url)
  if (typeof flags.source === 'string') {
    if (!['preview', 'kit', 'check', 'hash'].includes(mode)) fail('--source reads another token set for preview, kit, check or hash only; build always reads tokens.source', 2)
    config.tokens.source = rel(root, resolve(flags.source))
  }
  HEADER = `Generated by massimo tokens from ${config.tokens.source}. Do not edit by hand: change the tokens, then run ${scriptCommand(root, projectDir, 'tokens', 'build')}`
  const shown = (abs) => {
    const r = rel(root, abs)
    return r.startsWith('..') ? abs : r
  }

  if (mode === 'migrate') return migrate({ root, config, projectDir, configPath, flags, shown })
  if (mode === 'mirror') return mirrorCommand({ root, config, projectDir, flags, shown })
  const over = ['build', 'check'].includes(mode) ? overSources(root, config) : []
  if (over.length > 0) fail(`tokens.outputs writes ${over.map((o) => o.path).join(', ')}, which tokens.mirror reads as the source, and the build never writes over a file it mirrors. Point that output at another file.`)

  if (mode === 'extract') {
    // What the sources define, then the code's own values for the gaps.
    const { sources } = readSources(root, config)
    const audit = runAudit(root, config)
    const proposal = propose({ sources, audit, fromCss, minCount: Number(flags['min-count'] ?? 2), styling: config.styling })
    if (proposal.tokens.length === 0) fail('found nothing to propose: no style files, config, theme or token files, and no raw values in the code')
    const { tokens, losses, defaultMode } = draftFrom(proposal.tokens, config)
    const set = writeTokenSet({
      tokens,
      defaultMode,
      name: 'Draft tokens',
      description: 'Draft proposed by massimo from what this repo already uses. Nothing here is in use yet: review it with the tokens skill.',
    })
    const dir = join(projectDir, 'tokens', 'draft')
    for (const [name, text] of Object.entries(set)) writeText(join(dir, name), text)
    writeText(join(dir, 'report.md'), draftReport({ sources, audit, ...proposal, losses, count: tokens.length }))
    const fromCode = proposal.tokens.filter((t) => t.source === 'audit').length
    const files = new Set(proposal.tokens.filter((t) => t.source !== 'audit').map((t) => t.source)).size
    process.stdout.write(`massimo tokens extract: ${tokens.length} tokens (${tokens.length - fromCode} from ${files} ${files === 1 ? 'file' : 'files'}, ${fromCode} from the code), ${proposal.outliers.length} values not proposed; wrote ${shown(join(dir, 'tokens.resolver.json'))} and report.md\n`)
    return
  }

  const tokens = loadTokens(root, config, { draftOk: mode === 'kit' || mode === 'preview' })
  if (!tokens) {
    const message = config.tokens.mirror
      ? `no mirror of the style files at ${config.tokens.source} yet. Run: ${scriptCommand(root, projectDir, 'tokens', 'mirror')}`
      : `no tokens at ${config.tokens.source}. Run \`tokens.mjs extract\`, review the draft in tokens/draft/, then move it into tokens/.`
    if (mode === 'check') {
      process.stderr.write(`massimo tokens: ${message}\n`)
      process.exit(2)
    }
    fail(message)
  }
  // When reading found problems and no tokens, the problems explain the empty set.
  if (tokens.tokens.length === 0 && tokens.problems.some((p) => p.level === 'error')) throw new TokenProblems(tokens.problems)
  // A blank project still gets a kit, so the ux loop can start before there are tokens.
  if (tokens.tokens.length === 0 && mode !== 'kit') fail(`${tokens.origin === 'tokens' ? `${config.tokens.source} defines` : 'the style files define'} no tokens`)

  if (mode === 'figma') return figmaCommand({ root, config, projectDir, flags, shown, tokens })

  if (mode === 'hash') {
    process.stdout.write(`${tokensHash(root, tokens.files)}\n`)
    return
  }

  if (mode === 'build') {
    const { model, files } = buildOutputs(root, projectDir, config, tokens)
    warnAll(model)
    if (config.tokens.mirror && mirrorState(root, config, projectDir).stale.length > 0) {
      process.stderr.write(`massimo: warn: the mirror is behind the style files, so this build is from the CSS as it was; run ${scriptCommand(root, projectDir, 'tokens', 'mirror')} first\n`)
    }
    for (const f of files) writeText(f.path, f.text)
    process.stdout.write(`massimo tokens build: ${tokens.tokens.length} tokens; wrote ${files.map((f) => shown(f.path)).join(', ')}\n`)
    return
  }

  if (mode === 'kit') {
    const model = modelOf(tokens, config)
    warnAll(model)
    const path = join(projectDir, 'kit', 'kit.css')
    writeText(path, buildKit(model, tokens.origin, tokens.files, config))
    const from = tokens.origin === 'none' ? 'no tokens yet, so system defaults' : `${tokens.tokens.length} tokens from ${tokens.origin}`
    process.stdout.write(`massimo tokens kit: ${from}; wrote ${shown(path)}\n`)
    return
  }

  if (mode === 'preview') {
    const model = modelOf(tokens, config)
    warnAll(model)
    const kit = buildKit(model, tokens.origin, tokens.files, config)
    const path = join(projectDir, 'tokens', 'preview.html')
    writeText(path, buildPreview(model, tokens.origin, tokens.files, kit, config))
    process.stdout.write(`massimo tokens preview: ${tokens.tokens.length} tokens from ${tokens.origin}; wrote ${shown(path)}\n`)
    return
  }

  // check
  const { model, files } = buildOutputs(root, projectDir, config, tokens)
  warnAll(model)
  // A draft read with --source has no outputs of its own: only its contrast is checked.
  const stale = typeof flags.source === 'string' ? [] : files.filter((f) => !existsSync(f.path) || readFileSync(f.path, 'utf8') !== f.text)
  // With tokens.mirror on, the mirror itself is checked against the style files too.
  const behind = config.tokens.mirror && typeof flags.source !== 'string' ? mirrorState(root, config, projectDir).stale : []
  for (const f of behind) process.stderr.write(`  behind the style files: ${shown(f.path)}${existsSync(f.path) ? '' : ' (missing)'}\n`)
  const failures = contrastChecks(model).filter((c) => !c.pass)
  const strict = truthy(flags.strict)
  // The Figma library is a mirror, so drift is reported, never failed on.
  const mirror = tokens.origin === 'tokens' ? figmaMirror(root, projectDir, config, tokens.files) : null
  if (mirror && !mirror.current) {
    process.stderr.write(`  figma: the mirror was synced on ${mirror.syncedAt} from other tokens; run the figma skill's drift check\n`)
  }
  for (const f of stale) process.stderr.write(`  stale: ${shown(f.path)}${existsSync(f.path) ? '' : ' (missing)'}\n`)
  for (const c of failures) {
    process.stderr.write(`  ${strict ? 'fail' : 'warn'}: ${c.mode}: ${c.token} on ${c.on} is ${c.ratio.toFixed(2)}:1, needs ${c.needs}:1${c.use}\n`)
  }
  const parts = [`${tokens.tokens.length} tokens`, `${stale.length} stale`, `${failures.length} contrast ${failures.length === 1 ? 'failure' : 'failures'}`]
  if (mirror) parts.push(mirror.current ? 'figma mirror current' : 'figma mirror behind')
  if (config.tokens.mirror && typeof flags.source !== 'string') parts.push(behind.length > 0 ? 'mirror behind the style files' : 'mirror current')
  if (stale.length > 0 || behind.length > 0) {
    // A mirror brought up to date can change every output, so build follows it.
    const fixes = [...(behind.length > 0 ? ['mirror'] : []), 'build'].map((m) => scriptCommand(root, projectDir, 'tokens', m))
    process.stdout.write(`massimo tokens check: out of date (${parts.join(', ')}). Run: ${fixes.join(', then ')}\n`)
    process.exit(1)
  }
  if (failures.length > 0 && strict) {
    process.stdout.write(`massimo tokens check: contrast failures (${parts.join(', ')})\n`)
    process.exit(1)
  }
  process.stdout.write(`massimo tokens check: up to date (${parts.join(', ')})\n`)
}

const entry = process.argv[1] ? realpathSync(process.argv[1]) : ''
if (entry === fileURLToPath(import.meta.url)) {
  try {
    main()
  } catch (err) {
    fail(err instanceof Error ? err.message : String(err))
  }
}
