// Design tokens for massimo: extract a W3C DTCG draft from the CSS a repo
// already has, build every output from tokens.json (CSS, Tailwind, SCSS, JSON,
// TypeScript, Figma variables, the mockup kit), check they are not stale, and
// preview the set in one self-contained page.
//
// tokens.json is the source of truth: groups, `$type`, `$value`, `$description`,
// aliases like "{color.neutral.950}", and a `$extensions.massimo` block for
// modes (`modes: { dark: ... }`), a CSS variable override (`cssVar`), a contrast
// pair (`on` + `contrast`) and a Figma collection override. Output is
// deterministic, so `check` is a byte comparison.
//
// Usage:
//   node <project>/scripts/tokens.mjs extract    write a 2025.10 draft in tokens/draft/ from the style files
//   node <project>/scripts/tokens.mjs build      write every output, figma-variables.json and kit/kit.css
//   node <project>/scripts/tokens.mjs kit        write kit/kit.css only
//   node <project>/scripts/tokens.mjs check      rebuild in memory; exit 1 if stale (contrast failures too with --strict)
//   node <project>/scripts/tokens.mjs preview    write tokens/preview.html
//   node <project>/scripts/tokens.mjs hash       print the tokens' hash, as the Figma mirror records it
//   node <project>/scripts/tokens.mjs migrate    convert a tokens.json from before 0.2.0 to 2025.10 [--to legacy] [--force]
//   node <project>/scripts/tokens.mjs figma      --record <export.json> [--file-key K] | --drift <export.json>
//   node <project>/scripts/tokens.mjs mirror     write the token set as a mirror of the style files (tokens.mirror); --check to compare
// Shared flags: --root <dir> --config <file> --project-dir <dir>, and --source <file>
// to read another token set (a draft) for preview, kit, check or hash.
//
// With tokens.mirror on, the style files are the source instead: `mirror`
// writes the token set from them, keeping each CSS name, theme and scope, and
// every other command reads that set. `check` then also fails when the mirror
// is behind the CSS, and `build` never writes over a file it mirrors.

