// ── Output formats ──────────────────────────────────────────────────────────

const cssBlock = (selector, lines, indent = '') => [`${indent}${selector} {`, ...lines.map((l) => (l ? `${indent}  ${l}` : l)), `${indent}}`]

// Declarations for one mode. Linked output (var() for aliases) needs only the
// tokens with their own value in the mode, since an alias follows its target
// through the cascade. Literal output needs every value that differs from the
// default, or an alias would keep its default value in that mode.
function modeLines(model, mode, linked) {
  const lines = []
  for (const t of model.tokens) {
    const decls = declarations(model, t, mode, linked)
    if (mode === 'default' || (linked && mode in t.modes)) {
      for (const [name, text] of decls) lines.push(`${name}: ${text};`)
    } else if (!linked) {
      const base = new Map(declarations(model, t, 'default', false))
      for (const [name, text] of decls) if (base.get(name) !== text) lines.push(`${name}: ${text};`)
    }
  }
  return lines
}

// The selector a mode's block uses: tokens.selectors[mode] when set, else the
// dark selector with "dark" swapped for the mode's name, so `.dark` gives
// `.brand` and `[data-theme="dark"]` gives `[data-theme="brand"]`. The default
// mode's selector is the one the media query opts out of.
function modeSelector(config, model, mode) {
  const name = model.modeLabel(mode)
  const own = config.tokens.selectors?.[name]
  if (own) return own
  const dark = config.tokens.darkSelector
  if (name === 'dark') return dark
  return /dark/.test(dark) ? dark.replace(/dark/g, name) : `[data-theme="${name}"]`
}

// Every mode after the default, each under its selector; dark also under the
// media query when the app follows the system setting.
function modeBlocks(model, config) {
  const out = []
  for (const mode of model.modes.slice(1)) {
    const lines = modeLines(model, mode, true)
    if (lines.length === 0) continue
    out.push('', ...cssBlock(modeSelector(config, model, mode), lines))
    if (mode === 'dark' && config.tokens.darkMedia) {
      out.push('', '@media (prefers-color-scheme: dark) {', ...cssBlock(`:root:not(${modeSelector(config, model, 'default')})`, lines, '  '), '}')
    }
  }
  return out
}

function buildCss(model, config) {
  const root = []
  let group = null
  for (const t of model.tokens) {
    if (t.path[0] !== group) {
      group = t.path[0]
      if (root.length > 0) root.push('')
      root.push(`/* ${group.replace(/\*\//g, '* /')} */`)
    }
    for (const [name, text] of declarations(model, t, 'default', true)) root.push(`${name}: ${text};`)
  }
  const out = [`/* ${HEADER} */`, '', ...cssBlock(':root', root)]
  out.push(...modeBlocks(model, config))
  return `${out.join('\n')}\n`
}

// Where a token lands in Tailwind: a theme section and a key path inside it.
// A group named for the section is dropped from the key (`font.family.sans`
// is `sans` in fontFamily); a `$root` token is the section's DEFAULT.
function tailwindTarget(model, t) {
  const type = model.typeOf(t)
  const path = t.path.filter((p) => p !== '$root')
  const [first, ...rest] = path
  const under = (groups, sub = []) => {
    if (!groups.includes(first)) return path
    // A leaf named like the section (`motion.ease`) keeps its name.
    return sub.includes(rest[0]) && rest.length > 1 ? rest.slice(1) : rest
  }
  if (type === 'typography') return { section: 'fontSize', keys: under(['text', 'type', 'typography', 'font']), typography: true }
  if (type === 'color') return { section: 'colors', keys: under(['color', 'colors']) }
  if (type === 'fontFamily') return { section: 'fontFamily', keys: under(['font', 'fonts'], ['family', 'families']) }
  if (type === 'fontWeight') return { section: 'fontWeight', keys: under(['font', 'fonts'], ['weight', 'weights']) }
  if (type === 'cubicBezier') return { section: 'transitionTimingFunction', keys: under(['motion', 'ease', 'easing', 'transition'], ['ease', 'easing']) }
  if (type === 'shadow' || first === 'shadow') return { section: 'boxShadow', keys: under(['shadow', 'shadows', 'elevation']) }
  if (first === 'spacing' || first === 'space') return { section: 'spacing', keys: rest }
  if (first === 'radius' || first === 'radii') return { section: 'borderRadius', keys: rest }
  if (first === 'text') return { section: 'fontSize', keys: rest }
  if (first === 'font' && /^sizes?$/.test(rest[0] ?? '')) return { section: 'fontSize', keys: rest.slice(1) }
  // Tailwind 3 has theme sections for these; Tailwind 4 reads them as plain numbers.
  if (type === 'duration') return { section: 'transitionDuration', keys: under(['motion', 'duration', 'durations'], ['duration', 'durations']), v3only: true }
  if (type === 'number' && ['z', 'zIndex', 'z-index', 'layer'].includes(first)) return { section: 'zIndex', keys: rest, v3only: true }
  if (type === 'number' && first === 'opacity') return { section: 'opacity', keys: rest, v3only: true }
  return null
}

const TAILWIND4_PREFIX = {
  colors: '--color',
  spacing: '--spacing',
  borderRadius: '--radius',
  fontFamily: '--font',
  fontWeight: '--font-weight',
  fontSize: '--text',
  boxShadow: '--shadow',
  transitionTimingFunction: '--ease',
}

function buildTailwind4(model) {
  const lines = []
  for (const t of model.tokens) {
    const hit = tailwindTarget(model, t)
    if (!hit || hit.v3only || (hit.keys.length === 0 && hit.section !== 'spacing')) continue
    const name = [TAILWIND4_PREFIX[hit.section], ...hit.keys].join('-')
    if (hit.typography) {
      // Tailwind 4 reads a text size's line height, letter spacing and weight from `--text-x--<part>`.
      const parts = typographyParts(model, t).map(([, css]) => css)
      if (!parts.includes('font-size')) continue
      lines.push(`${name}: var(${t.cssVar}-font-size);`)
      for (const css of ['line-height', 'letter-spacing', 'font-weight']) {
        if (parts.includes(css)) lines.push(`${name}--${css}: var(${t.cssVar}-${css});`)
      }
      continue
    }
    lines.push(`${name}: var(${t.cssVar});`)
  }
  return [
    `/* ${HEADER} */`,
    '/* Utilities read these through var(), so the values (and the dark mode) come from the css output. */',
    '/* A token whose css variable has the same name as its theme variable maps to itself; that is intended, not a loop. */',
    '',
    ...cssBlock('@theme inline', lines),
    '',
  ].join('\n')
}

const IDENT = /^[A-Za-z_$][\w$]*$/

function setNested(obj, keys, value) {
  let cur = obj
  keys.forEach((key, i) => {
    const last = i === keys.length - 1
    if (last) {
      if (cur[key] && typeof cur[key] === 'object' && !Array.isArray(cur[key])) cur[key].DEFAULT = value
      else cur[key] = value
    } else {
      if (typeof cur[key] === 'string' || Array.isArray(cur[key])) cur[key] = { DEFAULT: cur[key] }
      cur[key] ??= {}
      cur = cur[key]
    }
  })
}

const jsString = (v) => `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

function objectLiteral(obj, depth = 0) {
  const pad = '  '.repeat(depth + 1)
  const valueText = (v) =>
    typeof v === 'string' ? jsString(v) : Array.isArray(v) ? `[${v.map(valueText).join(', ')}]` : objectLiteral(v, depth + 1)
  const lines = Object.keys(obj).map((k) => `${pad}${IDENT.test(k) ? k : jsString(k)}: ${valueText(obj[k])},`)
  return `{\n${lines.join('\n')}\n${'  '.repeat(depth)}}`
}

function buildTailwind3(model) {
  const theme = { colors: {}, spacing: {}, borderRadius: {}, fontFamily: {}, fontWeight: {}, fontSize: {}, boxShadow: {}, transitionTimingFunction: {}, transitionDuration: {}, zIndex: {}, opacity: {} }
  for (const t of model.tokens) {
    const hit = tailwindTarget(model, t)
    if (!hit) continue
    const keys = hit.keys.length > 0 ? hit.keys : ['DEFAULT']
    if (hit.typography) {
      // Tailwind 3 takes a font size as [size, { lineHeight, letterSpacing, fontWeight }].
      const parts = typographyParts(model, t).map(([key, css]) => [key, css])
      if (!parts.some(([key]) => key === 'fontSize')) continue
      const extra = {}
      for (const [key, css] of parts) if (['lineHeight', 'letterSpacing', 'fontWeight'].includes(key)) extra[key] = `var(${t.cssVar}-${css})`
      setNested(theme.fontSize, keys, Object.keys(extra).length > 0 ? [`var(${t.cssVar}-font-size)`, extra] : `var(${t.cssVar}-font-size)`)
      continue
    }
    setNested(theme[hit.section], keys, `var(${t.cssVar})`)
  }
  for (const k of Object.keys(theme)) if (Object.keys(theme[k]).length === 0) delete theme[k]
  return [
    `// ${HEADER}`,
    "// Use it as: module.exports = { theme: { extend: require('./tokens.tailwind.cjs') } }",
    '// Colours are var() references, so opacity modifiers (bg-primary/50) need channel-form variables.',
    `module.exports = ${objectLiteral(theme)}`,
    '',
  ].join('\n')
}

function buildScss(model) {
  const lines = [`// ${HEADER}`, '']
  let group = null
  for (const t of model.tokens) {
    if (t.path[0] !== group) {
      if (group !== null) lines.push('')
      group = t.path[0]
    }
    lines.push(`$${t.cssVar.replace(/^--/, '')}: var(${t.cssVar});`)
  }
  return `${lines.join('\n')}\n`
}

function buildJson(model) {
  const tokens = {}
  for (const t of model.tokens) {
    const values = {}
    for (const mode of model.modes) values[mode] = literal(model, t, mode)
    tokens[t.name] = { type: model.typeOf(t), cssVar: t.cssVar, values }
    if (t.deprecated) tokens[t.name].deprecated = t.deprecated
  }
  return jsonText({ $comment: HEADER, generatedBy: 'massimo tokens', modes: model.modes, tokens })
}

function buildTs(model) {
  const tree = {}
  for (const t of model.tokens) setNested(tree, t.path, `var(${t.cssVar})`)
  return [
    `// ${HEADER}`,
    '// Each leaf is the token as a CSS var() reference, so it follows the active theme.',
    `export const tokens = ${objectLiteral(tree)} as const`,
    '',
  ].join('\n')
}

// ── Figma variables and styles ─────────────────────────────────────────────

const figmaMode = (model, mode) => titleCase(model.modeLabel(mode))

// A token's value as CSS text without its CSS override: what the DTCG value
// says, which is what Figma and every place outside CSS should show.
function valueText(model, t, mode) {
  let depth = 0
  const ref = (alias) => {
    const next = model.byName.get(aliasPath(alias))
    if (++depth > 32) throw new Error(`reference ${alias} goes round in a cycle`)
    return cssText(model.typeOf(next), model.resolved(next, mode), ref)
  }
  return cssText(model.typeOf(t), model.resolved(t, mode), ref)
}

// Figma's units: px for lengths (a rem is 16px), ms for durations. A length in
// em depends on the text it sits in, so it has no Figma number.
const LENGTH_PX = /^(-?\d*\.?\d+)(px|rem)?$/
const TIME_MS = /^(-?\d*\.?\d+)(ms|s)$/
function figmaNumber(type, text) {
  const time = type === 'duration' && TIME_MS.exec(text)
  if (time) return round(parseFloat(time[1]) * (time[2] === 's' ? 1000 : 1), 4)
  const len = type !== 'duration' && LENGTH_PX.exec(text)
  if (len) return round(parseFloat(len[1]) * (len[2] === 'rem' ? 16 : 1), 4)
  return null
}

// Types Figma holds as styles or not at all, rather than as variables.
const STYLE_TYPES = new Set(['typography', 'shadow'])
const NO_VARIABLE = new Set(['cubicBezier', 'transition', 'gradient', 'border', 'strokeStyle', 'css'])

function figmaType(model, t) {
  const type = model.typeOf(t)
  if (STYLE_TYPES.has(type) || NO_VARIABLE.has(type)) return null
  const all = model.modes.map((m) => valueText(model, t, m))
  if (type === 'color') return all.every((v) => parseColor(v)) ? 'COLOR' : 'STRING'
  if (['dimension', 'number', 'fontWeight', 'duration'].includes(type)) return all.every((v) => figmaNumber(type, v) !== null) ? 'FLOAT' : 'STRING'
  return 'STRING'
}

const firstFamily = (text) => splitCss(text)[0]?.replace(/^(['"])(.*)\1$/, '$2') ?? text

function figmaValue(model, t, mode, type, collectionOf) {
  const next = model.target(t, mode)
  if (next) return { alias: figmaName(next), collection: collectionOf(next) }
  const text = valueText(model, t, mode)
  if (type === 'COLOR') {
    const c = parseColor(text)
    return { r: round(c.r), g: round(c.g), b: round(c.b), a: round(c.a) }
  }
  if (type === 'FLOAT') return figmaNumber(model.typeOf(t), text)
  return model.typeOf(t) === 'fontFamily' ? firstFamily(text) : text
}

const figmaName = (t) => t.path.filter((p) => p !== '$root').join('/')

// Where a variable may be picked in Figma, from its type and its name. The
// steps of a colour ramp (`neutral/500`) hide once semantic colours exist, so
// designers pick by meaning; a variable is never left on every scope.
function figmaScopes(model, t, type, collection, hideRamps) {
  const name = figmaName(t).toLowerCase()
  const kind = model.typeOf(t)
  const has = (re) => re.test(name)
  if (type === 'COLOR') {
    if (hideRamps && collection === 'Primitives' && /(^|[/-])\d+$/.test(name)) return []
    if (has(/shadow|elevation/)) return ['EFFECT_COLOR']
    if (has(/(^|\/)(bg|background|surface|canvas|base-\d+|backdrop|fill)\b/)) return ['FRAME_FILL', 'SHAPE_FILL']
    if (has(/(^|\/)(text|fg|foreground|content|ink)\b|-content$|(^|\/)on-/)) return ['TEXT_FILL']
    if (has(/(^|\/)(border|stroke|outline|divider|ring|separator)\b/)) return ['STROKE_COLOR']
    return ['ALL_FILLS', 'STROKE_COLOR']
  }
  if (type === 'STRING') return kind === 'fontFamily' ? ['FONT_FAMILY'] : []
  if (kind === 'fontWeight') return ['FONT_WEIGHT']
  if (kind === 'duration') return []
  if (has(/opacity|alpha/)) return ['OPACITY']
  if (has(/(^|\/)(z|z-index|zindex|layer)\b/)) return []
  if (has(/line-?height|leading/)) return ['LINE_HEIGHT']
  if (has(/letter|tracking/)) return ['LETTER_SPACING']
  if (has(/radius|radii|rounded|corner/)) return ['CORNER_RADIUS']
  if (has(/(^|\/)(text|font|type)(\/|-)(size|[a-z0-9-]*$)/) && kind === 'dimension') return ['FONT_SIZE']
  if (has(/border|stroke|outline|hairline/)) return ['STROKE_FLOAT']
  if (has(/blur|shadow/)) return ['EFFECT_FLOAT']
  if (has(/space|spacing|gap|padding|margin|inset|gutter/)) return ['GAP']
  if (has(/size|width|height|max|min|container|page/)) return ['WIDTH_HEIGHT']
  return kind === 'number' ? [] : ['GAP', 'WIDTH_HEIGHT']
}

// Figma names a font's weights itself; these are the usual names, to match
// against the styles the font actually has.
const FONT_STYLES = { 100: 'Thin', 200: 'ExtraLight', 300: 'Light', 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold', 800: 'ExtraBold', 900: 'Black', 950: 'ExtraBlack' }

// Figma variables, collections and modes, plus text styles from typography
// tokens and effect styles from shadow tokens, bound to the variables their
// parts point at. Each collection carries only the modes its own variables
// change in; an alias names the collection it points into.
function buildFigma(model) {
  const collectionOf = (t) => t.collection ?? (isAlias(t.value) ? 'Semantic' : 'Primitives')
  const members = new Map()
  const notMirrored = []
  const variableOf = new Map()
  for (const t of model.tokens) {
    const type = figmaType(model, t)
    const kind = model.typeOf(t)
    if (!type) {
      if (!STYLE_TYPES.has(kind)) notMirrored.push({ token: t.name, type: kind, reason: kind === 'css' ? 'a CSS-only value' : `Figma has no ${kind} variable` })
      continue
    }
    const name = collectionOf(t)
    if (!members.has(name)) members.set(name, [])
    members.get(name).push(t)
    variableOf.set(t.name, { variable: figmaName(t), collection: name, type })
  }
  const hideRamps = model.tokens.some((t) => model.typeOf(t) === 'color' && collectionOf(t) !== 'Primitives')
  const collection = (name) => {
    const list = members.get(name)
    const modes = model.modes.filter((m) => m === 'default' || list.some((t) => m in t.modes))
    const variables = list.map((t) => {
      const type = variableOf.get(t.name).type
      const values = {}
      for (const mode of modes) values[figmaMode(model, mode)] = figmaValue(model, t, mode, type, collectionOf)
      return { name: figmaName(t), type, scopes: figmaScopes(model, t, type, name, hideRamps), values, description: t.description, codeSyntax: { WEB: `var(${t.cssVar})` } }
    })
    return { name, modes: modes.map((m) => figmaMode(model, m)), variables }
  }

  // A part of a composite: its value in the default mode, and the variable it is bound to when it points at one.
  const part = (x, type) => {
    if (!isAlias(x)) return { text: cssText(type, x, (a) => valueText(model, model.byName.get(aliasPath(a)), 'default')), bound: null }
    const target = model.byName.get(aliasPath(x))
    return { text: valueText(model, target, 'default'), bound: variableOf.get(target.name) ?? null }
  }
  const bind = (into, field, p) => {
    if (p.bound) into[field] = { variable: p.bound.variable, collection: p.bound.collection }
  }
  const layersOf = (t) => {
    const v = model.resolved(t, 'default')
    return [].concat(v).flatMap((layer) => (isAlias(layer) ? layersOf(model.byName.get(aliasPath(layer))) : [layer]))
  }

  const textStyles = []
  const effectStyles = []
  for (const t of model.tokens) {
    const kind = model.typeOf(t)
    if (kind === 'typography') {
      const v = model.resolved(t, 'default')
      if (!v || typeof v !== 'object') continue
      const style = { name: figmaName(t), description: t.description }
      const boundVariables = {}
      if (v.fontFamily !== undefined) {
        const p = part(v.fontFamily, 'fontFamily')
        style.fontFamily = firstFamily(p.text)
        bind(boundVariables, 'fontFamily', p)
      }
      if (v.fontWeight !== undefined) {
        const p = part(v.fontWeight, 'fontWeight')
        style.fontWeight = Number(p.text)
        style.fontStyle = FONT_STYLES[style.fontWeight] ?? 'Regular'
        bind(boundVariables, 'fontWeight', p)
      }
      if (v.fontSize !== undefined) {
        const p = part(v.fontSize, 'dimension')
        style.fontSize = figmaNumber('dimension', p.text)
        bind(boundVariables, 'fontSize', p)
      }
      if (v.lineHeight !== undefined) {
        const p = part(v.lineHeight, 'number')
        const px = /(px|rem)$/.test(p.text) ? figmaNumber('dimension', p.text) : null
        style.lineHeight = px !== null ? { unit: 'PIXELS', value: px } : { unit: 'PERCENT', value: round(parseFloat(p.text) * 100, 4) }
        bind(boundVariables, 'lineHeight', p)
      }
      if (v.letterSpacing !== undefined) {
        const p = part(v.letterSpacing, 'dimension')
        const em = /^(-?\d*\.?\d+)em$/.exec(p.text)
        style.letterSpacing = em ? { unit: 'PERCENT', value: round(parseFloat(em[1]) * 100, 4) } : { unit: 'PIXELS', value: figmaNumber('dimension', p.text) ?? 0 }
        bind(boundVariables, 'letterSpacing', p)
      }
      if (Object.keys(boundVariables).length > 0) style.boundVariables = boundVariables
      textStyles.push(style)
    } else if (kind === 'shadow') {
      const layers = layersOf(t)
      if (!layers.every((l) => l && typeof l === 'object' && 'offsetX' in l)) {
        notMirrored.push({ token: t.name, type: kind, reason: 'a shadow written as CSS text; migrate it to a shadow object' })
        continue
      }
      const effects = layers.map((l) => {
        const boundVariables = {}
        const color = part(l.color ?? '#000000', 'color')
        const c = parseColor(color.text) ?? { r: 0, g: 0, b: 0, a: 1 }
        bind(boundVariables, 'color', color)
        const effect = { type: l.inset ? 'INNER_SHADOW' : 'DROP_SHADOW', color: { r: round(c.r), g: round(c.g), b: round(c.b), a: round(c.a) } }
        const [x, y, blur, spread] = [['offsetX', l.offsetX], ['offsetY', l.offsetY], ['radius', l.blur], ['spread', l.spread]].map(([field, value]) => {
          const p = part(value ?? '0px', 'dimension')
          bind(boundVariables, field, p)
          return figmaNumber('dimension', p.text) ?? 0
        })
        Object.assign(effect, { offset: { x, y }, radius: blur, spread })
        if (Object.keys(boundVariables).length > 0) effect.boundVariables = boundVariables
        return effect
      })
      effectStyles.push({ name: figmaName(t), description: t.description, effects })
    }
  }

  const order = ['Primitives', 'Semantic', ...[...members.keys()].filter((k) => k !== 'Primitives' && k !== 'Semantic').sort(compare)]
  return jsonText({
    $comment: HEADER,
    generatedBy: 'massimo tokens',
    format: FORMAT_VERSION,
    defaultMode: figmaMode(model, 'default'),
    collections: order.filter((n) => members.has(n)).map(collection),
    textStyles,
    effectStyles,
    notMirrored,
  })
}

// ── DESIGN.md ───────────────────────────────────────────────────────────────

// A path with its group name dropped (`color.bg` is `bg` under colors).
const within = (path, groups) => {
  const p = path.filter((x) => x !== '$root')
  const rest = groups.includes(p[0]) ? p.slice(1) : p
  return rest.length > 0 ? rest : ['default']
}

// The token set as DESIGN.md: colours, typography, radii and spacing in the
// front matter (the default theme), with references kept between colours,
// and the rest in its prose sections, with the components' rules from the graph.
function buildDesignMd(model, config, root, projectDir) {
  const pkg = readJson(join(root, 'package.json'), {}) ?? {}
  const name = config.name ?? pkg.name ?? 'Design system'
  const typeOf = (t) => model.typeOf(t)
  const colorGroups = ['color', 'colors']
  const colours = model.tokens.filter((t) => typeOf(t) === 'color')
  const colourNames = new Set(colours.map((t) => t.name))
  // DESIGN.md reads hex and the CSS colour functions, but not color() or a
  // "none" component; those colours go in as their nearest sRGB hex.
  const approximated = []
  const colors = colours.map((t) => {
    const next = model.target(t, 'default')
    const path = within(t.path, colorGroups)
    if (next && colourNames.has(next.name)) return { path, value: `{colors.${within(next.path, colorGroups).join('.')}}`, description: t.description }
    const css = valueText(model, t, 'default')
    const readable = /^(#|rgba?\(|hsla?\(|hwb\(|oklch\(|oklab\(|lab\(|lch\()/.test(css) && !/\bnone\b/.test(css)
    const value = readable || !parseColor(css) ? css : toHex(parseColor(css))
    if (value !== css) approximated.push({ name: `colors.${path.join('.')}`, css })
    return { path, value, description: t.description }
  })
  const typography = model.tokens
    .filter((t) => typeOf(t) === 'typography')
    .map((t) => {
      const v = model.resolved(t, 'default')
      const part = (key, type) => (v[key] === undefined ? undefined : isAlias(v[key]) ? valueText(model, model.byName.get(aliasPath(v[key])), 'default') : cssText(type, v[key]))
      const lineHeight = part('lineHeight', 'number')
      const value = {
        fontFamily: v.fontFamily === undefined ? undefined : firstFamily(part('fontFamily', 'fontFamily')),
        fontSize: part('fontSize', 'dimension'),
        fontWeight: v.fontWeight === undefined ? undefined : Number(part('fontWeight', 'fontWeight')),
        lineHeight: lineHeight === undefined ? undefined : /^-?[\d.]+$/.test(lineHeight) ? Number(lineHeight) : lineHeight,
        letterSpacing: part('letterSpacing', 'dimension'),
      }
      return { path: within(t.path, ['text', 'type', 'typography', 'font']), value, description: t.description }
    })
  const dims = (groups) =>
    model.tokens
      .filter((t) => typeOf(t) === 'dimension' && groups.includes(t.path[0]))
      .map((t) => ({ path: within(t.path, groups), value: valueText(model, t, 'default'), description: t.description }))
  const shadows = model.tokens.filter((t) => typeOf(t) === 'shadow').map((t) => ({ name: t.name, css: valueText(model, t, 'default'), description: t.description }))
  const contrast = model.tokens.filter((t) => t.on).map((t) => ({ token: t.name, on: t.on, needs: t.contrast, use: t.use ? USE_TEXT[t.use].replace(/^for /, '') : null }))
  const graph = readJson(join(projectDir, 'graph.json'), null)
  refuseNewer('graph', graph?.version, 'graph.json')
  const components = (graph?.nodes ?? [])
    .filter((n) => n.rules?.['use-when'] || n.rules?.never)
    .map((n) => ({ name: n.name, useWhen: n.rules['use-when'] ?? null, never: n.rules.never ?? null }))
  return designMd({
    name,
    description: config.description,
    source: config.tokens.source,
    defaultMode: model.defaultMode,
    otherModes: model.modes.slice(1).map((m) => model.modeLabel(m)),
    header: `${HEADER}. Written as DESIGN.md format version ${DESIGN_MD.version} (google-labs-code/design.md ${DESIGN_MD.release}).`,
    colors,
    approximated,
    typography,
    rounded: dims(['radius', 'radii', 'rounded']),
    spacing: dims(['spacing', 'space']),
    shadows,
    contrast,
    components,
  })
}

// ── The kit: literal values for mockups ─────────────────────────────────────

const BODY_FONT = ['--font-sans', '--font-body', '--font-family', '--font-base']
const BODY_COLOR = ['--color-base-content', '--color-fg', '--color-foreground', '--color-text', '--color-text-default', '--color-fg-default', '--color-content', '--color-on-surface']
const BODY_BG = ['--color-base-100', '--color-bg', '--color-background', '--color-bg-default', '--color-surface', '--color-surface-default']

// The kit answers to the app's own theme selectors and to `data-theme`, which
// the canvas and the preview flip to show every mode.
const kitSelector = (config, model, mode) =>
  [...new Set([modeSelector(config, model, mode), `[data-theme="${model.modeLabel(mode)}"]`])].join(', ')

function buildKit(model, origin, files, config) {
  const present = new Set(model.tokens.flatMap((t) => cssNames(model, t)))
  const pick = (names) => names.find((n) => present.has(n))
  const font = pick(BODY_FONT)
  const fg = pick(BODY_COLOR)
  const bg = pick(BODY_BG)
  const source =
    origin === 'tokens'
      ? `Source: ${config.tokens.source}.`
      : origin === 'none'
        ? 'No tokens yet: mockups use system defaults until the tokens phase.'
        : `Source: custom properties extracted from ${files.join(', ') || 'the style files'} (no tokens.json yet).`
  const out = [`/* ${HEADER} */`, `/* ${source} Link this file from mockups so they look like the product. */`, '']
  out.push(...cssBlock(':root', ['color-scheme: light;', ...modeLines(model, 'default', false)]))
  const dark = model.modes.includes('dark') ? modeLines(model, 'dark', false) : []
  out.push('', ...cssBlock(kitSelector(config, model, 'dark'), ['color-scheme: dark;', ...dark]))
  if (dark.length > 0 && config.tokens.darkMedia) {
    const optOut = [...new Set([modeSelector(config, model, 'default'), '[data-theme="light"]', `[data-theme="${model.defaultMode}"]`])]
    out.push('', '@media (prefers-color-scheme: dark) {', ...cssBlock(`:root${optOut.map((s) => `:not(${s})`).join('')}`, ['color-scheme: dark;', ...dark], '  '), '}')
  }
  for (const mode of model.modes.filter((m) => m !== 'default' && m !== 'dark')) {
    out.push('', ...cssBlock(kitSelector(config, model, mode), modeLines(model, mode, false)))
  }
  out.push('', '*, *::before, *::after {', '  box-sizing: border-box;', '}')
  const body = ['margin: 0;', `font-family: ${font ? `var(${font})` : 'system-ui, sans-serif'};`]
  if (fg) body.push(`color: var(${fg});`)
  if (bg) body.push(`background: var(${bg});`)
  out.push('', ...cssBlock('body', body))
  return `${out.join('\n')}\n`
}

// ── Contrast ────────────────────────────────────────────────────────────────

// What a contrast pair is for, in words, by WCAG 2.2: text needs 4.5:1, large
// text 3:1, and UI parts and focus indicators 3:1 against what they sit on.
const USE_TEXT = { text: 'for text', 'large-text': 'for large text', ui: 'for UI', focus: 'for a focus indicator' }

// Every contrast pair in every theme. A translucent colour is composited
// over what it sits on first.
// A colour in a mode: its CSS, or else its value, since a channel triplet's
// exact CSS (`236 229 209`) is not a colour on its own.
const colorIn = (model, t, mode) => parseColor(literal(model, t, mode)) ?? parseColor(cssText('color', model.resolved(t, mode), () => ''))

function contrastChecks(model) {
  const results = []
  for (const t of model.tokens) {
    if (!t.on) continue
    const bgToken = model.byName.get(t.on)
    for (const mode of model.modes) {
      const fg = colorIn(model, t, mode)
      const bg = colorIn(model, bgToken, mode)
      if (!fg || !bg) continue
      const ratio = contrastRatio(fg, bg)
      const use = t.use ? ` ${USE_TEXT[t.use]}` : ''
      results.push({ token: t.name, on: t.on, mode: model.modeLabel(mode), ratio, needs: t.contrast, use, pass: ratio >= t.contrast })
    }
  }
  return results
}

