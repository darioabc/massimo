// Design tokens for massimo: extract a W3C DTCG draft from the CSS a repo
// already has, build every output from tokens.json (CSS, Tailwind, SCSS, JSON,
// TypeScript, Figma variables, the mockup kit), check they are not stale, and
// preview the set in one self-contained page.
//
// tokens.json is the source of truth: groups, `$type`, `$value`, `$description`,
// aliases like "{color.neutral.950}", and a `$extensions.massimo` block for
// modes (`modes: { dark: ... }`), a CSS variable override (`cssVar`), a contrast
// pair (`on` + `contrast`) and a Figma collection override. Output is
// deterministic, so `check` is a byte comparison.
//
// Usage:
//   node design-system/scripts/tokens.mjs extract    write tokens/tokens.draft.json from the style files
//   node design-system/scripts/tokens.mjs build      write every output, figma-variables.json and kit/kit.css
//   node design-system/scripts/tokens.mjs kit        write kit/kit.css only
//   node design-system/scripts/tokens.mjs check      rebuild in memory; exit 1 if stale (contrast failures too with --strict)
//   node design-system/scripts/tokens.mjs preview    write tokens/preview.html
//   node design-system/scripts/tokens.mjs hash       print the tokens' hash, as the Figma mirror records it
// Shared flags: --root <dir> --config <file> --project-dir <dir>

