function buildPreview(model, origin, files, kit, config) {
  const contrast = contrastChecks(model)
  const notesFor = (name) =>
    contrast
      .filter((c) => c.token === name)
      .map((c) => `<div class="pv-note ${c.pass ? 'ok' : 'bad'}">${c.pass ? 'passes' : 'fails'} ${c.needs}:1 on ${esc(c.on)} (${esc(c.mode)}): ${c.ratio.toFixed(2)}:1</div>`)
      .join('')
  const valueNote = (t) => {
    const parts = model.modes.map((m) => ({ m, v: literal(model, t, m) }))
    const distinct = new Set(parts.map((p) => p.v))
    return distinct.size === 1 ? esc(parts[0].v) : parts.map((p) => `${esc(p.m)} ${esc(p.v)}`).join('<br>')
  }
  const label = (t) => `<div class="pv-name">${esc(t.name)}</div><div class="pv-var">${esc(t.cssVar)}</div>`

  const colors = model.tokens.filter((t) => model.typeOf(t) === 'color')
  const byGroup = new Map()
  for (const t of colors) {
    if (!byGroup.has(t.path[0])) byGroup.set(t.path[0], [])
    byGroup.get(t.path[0]).push(t)
  }
  const sections = []
  for (const [group, list] of byGroup) {
    const cards = list
      .map((t) => `<div class="pv-card"><div class="pv-swatch" style="background: var(${esc(t.cssVar)})"></div><div class="pv-meta">${label(t)}<div class="pv-value">${valueNote(t)}</div>${notesFor(t.name)}</div></div>`)
      .join('')
    sections.push(`<section class="pv-section"><h2>${group === 'color' ? 'Colour' : `Colour: ${esc(group)}`}</h2><div class="pv-grid">${cards}</div></section>`)
  }

  const rows = (title, list, render) =>
    list.length === 0
      ? ''
      : `<section class="pv-section"><h2>${title}</h2>${list.map((t) => `<div class="pv-row"><div>${label(t)}<div class="pv-value">${valueNote(t)}</div></div><div>${render(t)}</div></div>`).join('')}</section>`
  const notColor = model.tokens.filter((t) => model.typeOf(t) !== 'color')
  const sizes = notColor.filter((t) => t.path[0] === 'text' || (t.path[0] === 'font' && /^sizes?$/.test(t.path[1] ?? '')))
  const families = notColor.filter((t) => model.typeOf(t) === 'fontFamily')
  const spacing = notColor.filter((t) => t.path[0] === 'spacing' && model.typeOf(t) === 'dimension')
  const radii = notColor.filter((t) => t.path[0] === 'radius')
  const shadows = notColor.filter((t) => t.path[0] === 'shadow')
  const shown = new Set([...sizes, ...families, ...spacing, ...radii, ...shadows])
  const rest = notColor.filter((t) => !shown.has(t))
  sections.push(rows('Type scale', sizes, (t) => `<p class="pv-sample" style="font-size: var(${esc(t.cssVar)})">The quick brown fox jumps over the lazy dog</p>`))
  sections.push(rows('Font families', families, (t) => `<p class="pv-sample" style="font-family: var(${esc(t.cssVar)}); font-size: 22px">Sphinx of black quartz, judge my vow</p>`))
  sections.push(rows('Spacing', spacing, (t) => `<div class="pv-bar" style="width: var(${esc(t.cssVar)})"></div>`))
  sections.push(rows('Radii', radii, (t) => `<div class="pv-box" style="border-radius: var(${esc(t.cssVar)})"></div>`))
  sections.push(rows('Shadows', shadows, (t) => `<div class="pv-box" style="box-shadow: var(${esc(t.cssVar)})"></div>`))
  sections.push(rows('Other tokens', rest, () => ''))

  const draft =
    origin === 'draft'
      ? `<div class="pv-draft">This is a draft extracted from ${esc(files.join(', ') || 'the style files')}. There is no tokens.json yet; approve this, then save it as tokens.json.</div>`
      : ''
  const dark = config.tokens.darkMedia ? 'matchMedia("(prefers-color-scheme: dark)").matches' : 'false'
  return `<!doctype html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Design tokens preview</title>
<!-- ${HEADER} -->
<style>
${kit.trim()}
${PREVIEW_CSS.trim()}
</style>
</head>
<body>
<div class="pv-page">
<div class="pv-top"><div><h1>Design tokens</h1><p>${model.tokens.length} tokens from ${origin === 'draft' ? 'the style files' : 'tokens.json'}. Switch the theme to check every mode.</p></div><button class="pv-toggle" type="button" id="pv-toggle">Switch to dark</button></div>
${draft}
${sections.join('\n')}
</div>
<script>
(function () {
  var root = document.documentElement
  var button = document.getElementById('pv-toggle')
  function set(theme) {
    root.setAttribute('data-theme', theme)
    button.textContent = theme === 'dark' ? 'Switch to light' : 'Switch to dark'
  }
  set(${dark} ? 'dark' : 'light')
  button.addEventListener('click', function () { set(root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark') })
})()
</script>
</body>
</html>
`
}

// ── Orchestration ───────────────────────────────────────────────────────────

// Every file `build` writes, as { path (absolute), text }. Throws on a bad token set.
function buildOutputs(root, projectDir, config, tokens) {
  const model = buildModel(tokens.tokens)
  const out = []
  for (const output of config.tokens.outputs ?? []) {
    if (!FORMATS.includes(output.format)) {
      throw new Error(`tokens.outputs: unknown format "${output.format}". Use one of: ${FORMATS.join(', ')}.`)
    }
    const text = {
      css: () => buildCss(model, config),
      tailwind4: () => buildTailwind4(model),
      tailwind3: () => buildTailwind3(model),
      scss: () => buildScss(model),
      json: () => buildJson(model),
      ts: () => buildTs(model),
    }[output.format]()
    out.push({ path: join(root, output.path), text })
  }
  out.push({ path: join(projectDir, 'tokens', 'figma-variables.json'), text: buildFigma(model) })
  out.push({ path: join(projectDir, 'kit', 'kit.css'), text: buildKit(model, tokens.origin, tokens.files) })
  return { model, files: out }
}

const BOOLEAN_FLAGS = new Set(['strict'])
const truthy = (v) => v === true || v === 'true'

function main() {
  const argv = process.argv.slice(2).map((a) => (a.startsWith('--') && BOOLEAN_FLAGS.has(a.slice(2)) ? `${a}=true` : a))
  const { _: positionals, flags } = parseArgs(argv)
  const mode = positionals[0]
  const MODES = ['extract', 'build', 'kit', 'check', 'preview']
  if (!MODES.includes(mode)) fail(`usage: tokens.mjs <${MODES.join('|')}> [--strict]`, 2)
  const { root, config, projectDir } = loadConfig(flags)
  const shown = (abs) => {
    const r = rel(root, abs)
    return r.startsWith('..') ? abs : r
  }

  if (mode === 'extract') {
    if (config.tokens.styleFiles.length === 0) fail('tokens.styleFiles is empty; list the stylesheets that define the custom properties')
    const draft = extractDraft(root, config)
    if (draft.files.length === 0) fail(`no style files matched tokens.styleFiles (${config.tokens.styleFiles.join(', ')})`)
    const path = join(projectDir, 'tokens', 'tokens.draft.json')
    writeText(path, jsonText(draft.doc))
    process.stdout.write(`massimo tokens extract: ${draft.count} tokens from ${draft.files.length} ${draft.files.length === 1 ? 'file' : 'files'}; wrote ${shown(path)}\n`)
    return
  }

  const tokens = loadTokens(root, config, { draftOk: mode === 'kit' || mode === 'preview' })
  if (!tokens) {
    const message = `no tokens.json at ${config.tokens.source}. Run \`tokens.mjs extract\`, review the draft, then save it there.`
    if (mode === 'check') {
      process.stderr.write(`massimo tokens: ${message}\n`)
      process.exit(2)
    }
    fail(message)
  }
  if (tokens.tokens.length === 0) fail(`${tokens.origin === 'draft' ? 'the style files define' : config.tokens.source + ' defines'} no tokens`)

  if (mode === 'build') {
    const { files } = buildOutputs(root, projectDir, config, tokens)
    for (const f of files) writeText(f.path, f.text)
    process.stdout.write(`massimo tokens build: ${tokens.tokens.length} tokens; wrote ${files.map((f) => shown(f.path)).join(', ')}\n`)
    return
  }

  if (mode === 'kit') {
    const model = buildModel(tokens.tokens)
    const path = join(projectDir, 'kit', 'kit.css')
    writeText(path, buildKit(model, tokens.origin, tokens.files))
    process.stdout.write(`massimo tokens kit: ${tokens.tokens.length} tokens from ${tokens.origin}; wrote ${shown(path)}\n`)
    return
  }

  if (mode === 'preview') {
    const model = buildModel(tokens.tokens)
    const kit = buildKit(model, tokens.origin, tokens.files)
    const path = join(projectDir, 'tokens', 'preview.html')
    writeText(path, buildPreview(model, tokens.origin, tokens.files, kit, config))
    process.stdout.write(`massimo tokens preview: ${tokens.tokens.length} tokens from ${tokens.origin}; wrote ${shown(path)}\n`)
    return
  }

  // check
  const { model, files } = buildOutputs(root, projectDir, config, tokens)
  const stale = files.filter((f) => !existsSync(f.path) || readFileSync(f.path, 'utf8') !== f.text)
  const failures = contrastChecks(model).filter((c) => !c.pass)
  const strict = truthy(flags.strict)
  for (const f of stale) process.stderr.write(`  stale: ${shown(f.path)}${existsSync(f.path) ? '' : ' (missing)'}\n`)
  for (const c of failures) {
    process.stderr.write(`  ${strict ? 'fail' : 'warn'}: ${c.token} on ${c.on} (${c.mode}) is ${c.ratio.toFixed(2)}:1, needs ${c.needs}:1\n`)
  }
  const parts = [`${tokens.tokens.length} tokens`, `${stale.length} stale`, `${failures.length} contrast ${failures.length === 1 ? 'failure' : 'failures'}`]
  if (stale.length > 0) {
    process.stdout.write(`massimo tokens check: out of date (${parts.join(', ')}). Run: node design-system/scripts/tokens.mjs build\n`)
    process.exit(1)
  }
  if (failures.length > 0 && strict) {
    process.stdout.write(`massimo tokens check: contrast failures (${parts.join(', ')})\n`)
    process.exit(1)
  }
  process.stdout.write(`massimo tokens check: up to date (${parts.join(', ')})\n`)
}

const entry = process.argv[1] ? realpathSync(process.argv[1]) : ''
if (entry === fileURLToPath(import.meta.url)) {
  try {
    main()
  } catch (err) {
    fail(err instanceof Error ? err.message : String(err))
  }
}
