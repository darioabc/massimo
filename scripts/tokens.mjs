// A family name as CSS: bare when it is one identifier, quoted (and escaped) otherwise.
const quoteFamily = (name) => {
  if (/^[\w-]+$/.test(name) || GENERIC_FAMILY.test(name) || /^(["']).*\1$/.test(name)) return name
  return `"${name.replace(/["\\]/g, (c) => `\\${c}`)}"`
}

// DTCG fontWeight keywords, as the numbers CSS needs.
const FONT_WEIGHTS = {
  thin: 100, hairline: 100, 'extra-light': 200, 'ultra-light': 200, light: 300, normal: 400, regular: 400, book: 400,
  medium: 500, 'semi-bold': 600, 'demi-bold': 600, bold: 700, 'extra-bold': 800, 'ultra-bold': 800, black: 900,
  heavy: 900, 'extra-black': 950, 'ultra-black': 950,
}

// DTCG colour spaces CSS writes with its own function, and those it writes with color().
const CSS_COLOR_SPACES = new Set(['srgb', 'srgb-linear', 'hsl', 'hwb', 'lab', 'lch', 'oklab', 'oklch', 'display-p3', 'a98-rgb', 'prophoto-rgb', 'rec2020', 'xyz-d65', 'xyz-d50'])

const numText = (n) => (n === 'none' ? 'none' : String(round(n)))

// A DTCG colour object as CSS: hex for sRGB, the space's own function or
// color() otherwise; a space CSS cannot write falls back to the hex.
function colorObjectText(v) {
  const { colorSpace, components } = v
  if (!Array.isArray(components) || components.length !== 3 || !components.every((c) => c === 'none' || typeof c === 'number')) {
    throw new Error(`colour ${JSON.stringify(v)} needs three numeric components`)
  }
  if (CSS_COLOR_SPACES.has(colorSpace)) return colorCss(v)
  if (typeof v.hex === 'string') return v.hex
  throw new Error(`colour space "${colorSpace}" is not one CSS can write`)
}

const unitText = (v) => (v && typeof v === 'object' && 'value' in v ? `${numText(v.value)}${v.unit ?? 'px'}` : String(v))

const TYPOGRAPHY_PARTS = [
  ['fontFamily', 'font-family', 'fontFamily'],
  ['fontSize', 'font-size', 'dimension'],
  ['fontWeight', 'font-weight', 'fontWeight'],
  ['lineHeight', 'line-height', 'number'],
  ['letterSpacing', 'letter-spacing', 'dimension'],
]

// What a value with no usable `$type` looks like, for the old dialect's untyped composites.
function shapeType(v) {
  if (Array.isArray(v)) return v.length > 0 && v.every((x) => x && typeof x === 'object' && 'offsetX' in x) ? 'shadow' : null
  if (!v || typeof v !== 'object') return null
  if ('colorSpace' in v) return 'color'
  if ('offsetX' in v) return 'shadow'
  if ('fontFamily' in v || 'fontSize' in v) return 'typography'
  if ('timingFunction' in v) return 'transition'
  if ('width' in v && 'style' in v) return 'border'
  if ('value' in v) return 'dimension'
  return null
}

// A DTCG value as CSS text. `ref` turns a "{path}" reference into CSS: the
// var() of its token where the output stays linked, the resolved literal where
// it does not. References may sit inside composites (a shadow's colour).
function cssText(type, v, ref = (alias) => alias) {
  if (isAlias(v)) return ref(v)
  const sub = (t, x) => cssText(t, x, ref)
  if (typeof v === 'string' && type === 'fontFamily') return v.includes(',') || /^['"]/.test(v.trim()) ? v.trim() : quoteFamily(v.trim())
  if (typeof v === 'string' && type === 'fontWeight') return String(FONT_WEIGHTS[v.trim()] ?? v.trim())
  if (typeof v === 'string') return v.trim()
  if (typeof v === 'number') return type === 'dimension' ? `${v}px` : String(v)
  const kind = type && type !== 'string' ? type : shapeType(v)
  switch (kind) {
    case 'color':
      return v && typeof v === 'object' ? colorObjectText(v) : String(v)
    case 'dimension':
    case 'duration':
      return unitText(v)
    case 'fontFamily':
      return Array.isArray(v) ? v.map(quoteFamily).join(', ') : String(v)
    case 'fontWeight':
      return String(FONT_WEIGHTS[v] ?? v)
    case 'cubicBezier':
      return Array.isArray(v) ? `cubic-bezier(${v.map((n) => sub('number', n)).join(', ')})` : String(v)
    case 'strokeStyle':
      // CSS has no dash pattern for borders: an object form becomes `dashed`.
      return typeof v === 'string' ? v.trim() : 'dashed'
    case 'shadow':
      return [].concat(v).map((s) => {
        if (isAlias(s)) return ref(s)
        const parts = [s.offsetX, s.offsetY, s.blur, s.spread].filter((x) => x !== undefined).map((x) => sub('dimension', x))
        return `${s.inset ? 'inset ' : ''}${parts.join(' ')} ${sub('color', s.color ?? '#000000')}`
      }).join(', ')
    case 'border':
      return [sub('dimension', v.width), sub('strokeStyle', v.style), sub('color', v.color)].join(' ')
    case 'transition':
      return [['duration', v.duration], ['cubicBezier', v.timingFunction], ['duration', v.delay]]
        .filter(([, x]) => x !== undefined)
        .map(([t, x]) => sub(t, x))
        .join(' ')
    case 'gradient':
      return `linear-gradient(${[].concat(v).map((stop) => {
        if (isAlias(stop)) return ref(stop)
        const at = isAlias(stop.position) ? `calc(${ref(stop.position)} * 100%)` : `${numText(stop.position * 100)}%`
        return `${sub('color', stop.color)} ${at}`
      }).join(', ')})`
    case 'typography': {
      // The `font` shorthand; letter-spacing has no place in it and lives in its own variable.
      const size = v.fontSize === undefined ? null : sub('dimension', v.fontSize)
      const sized = size && v.lineHeight !== undefined ? `${size}/${sub('number', v.lineHeight)}` : size
      return [v.fontWeight === undefined ? null : sub('fontWeight', v.fontWeight), sized, v.fontFamily === undefined ? null : sub('fontFamily', v.fontFamily)]
        .filter(Boolean)
        .join(' ')
    }
    default:
      if (Array.isArray(v)) return v.join(', ')
      return String(v)
  }
}

// ── The token model ─────────────────────────────────────────────────────────

const MODE_NAME = /^[a-z][a-z0-9-]*$/i

// Everything wrong with a token set, as `{ level, path, message }`. Reading
// collects every problem instead of stopping at the first, so one run shows
// every fix; a build with any error throws them all at once.
export class TokenProblems extends Error {
  constructor(problems) {
    const errors = problems.filter((p) => p.level === 'error')
    super(`${errors.length} ${errors.length === 1 ? 'problem' : 'problems'} in the tokens:\n${errors.map((p) => `  error: ${p.path}: ${p.message}`).join('\n')}`)
    this.problems = problems
  }
}

// Why a string cannot go into a CSS declaration as it is, or null when it can.
// Values reach stylesheets, `<style>` blocks and HTML attributes, so a `;`, a
// brace, an angle bracket or an unclosed quote could end the declaration.
function unsafeCss(s) {
  if (/[;{}<>\\\u0000-\u001f\u007f]/.test(s)) return 'has a character a CSS value cannot hold here (; { } < > \\ or a control character)'
  if (s.includes('/*') || s.includes('*/')) return 'has a CSS comment marker'
  let depth = 0
  let quote = null
  for (const c of s) {
    if (quote) {
      if (c === quote) quote = null
    } else if (c === '"' || c === "'") quote = c
    else if (c === '(') depth++
    else if (c === ')' && --depth < 0) return 'has a ) with no ('
  }
  if (quote) return 'has a quote that is never closed'
  if (depth > 0) return 'has a ( that is never closed'
  return null
}

// Every literal string inside a value, as [where, text]; references are skipped.
function* stringLeaves(v, where = '') {
  if (typeof v === 'string') {
    if (!isAlias(v)) yield [where, v]
  } else if (Array.isArray(v)) {
    for (let i = 0; i < v.length; i++) yield* stringLeaves(v[i], where ? `${where}[${i}]` : `[${i}]`)
  } else if (v && typeof v === 'object') {
    for (const [k, x] of Object.entries(v)) yield* stringLeaves(x, where ? `${where}.${k}` : k)
  }
}

// The token model every output is built from. `options.defaultMode` names the
// default context when a resolver document set it.
function buildModel(tokens, config, problems = [], options = {}) {
  // A cycle is found once from each token in it; it is one problem.
  const cycleKey = (message) => (message.startsWith('alias cycle: ') ? [...new Set(message.slice(13).split(' -> '))].sort().join(' ') : null)
  const report = (path, message, level = 'error') => {
    const key = cycleKey(message)
    const seen = problems.some((p) => (key ? cycleKey(p.message) === key : p.message === message && p.path === path))
    if (!seen) problems.push({ level, path, message })
  }
  const byName = new Map(tokens.map((t) => [t.name, t]))
  let defaultMode = options.defaultMode ?? config.tokens.defaultMode ?? 'light'
  if (!MODE_NAME.test(defaultMode)) {
    report('tokens.defaultMode', `"${defaultMode}" must be a plain name such as light`)
    defaultMode = 'light'
  }
  const modeNames = new Set()
  for (const t of tokens) {
    for (const m of Object.keys(t.modes)) {
      if (m === 'default' || m === defaultMode) {
        report(t.name, `"${m}" is the default mode; put its value in $value, not in $extensions.massimo.modes`)
      } else if (!MODE_NAME.test(m)) {
        report(t.name, `mode "${m}" must be a plain name such as dark`)
      } else {
        modeNames.add(m)
      }
    }
  }
  // A resolver document's own context order; otherwise dark first, then by name.
  const order = options.modeOrder ?? []
  const rank = (m) => (order.includes(m) ? order.indexOf(m) : order.length)
  const modes = ['default', ...[...modeNames].sort((a, b) => rank(a) - rank(b) || (a === 'dark' ? -1 : b === 'dark' ? 1 : compare(a, b)))]
  const modeLabel = (mode) => (mode === 'default' ? defaultMode : mode)

  const raw = (t, mode) => (mode === 'default' || !(mode in t.modes) ? t.value : t.modes[mode])
  const target = (t, mode) => {
    const v = raw(t, mode)
    if (!isAlias(v)) return null
    const next = byName.get(aliasPath(v))
    if (!next) throw new Error(`alias ${v} points at a token that does not exist`)
    return next
  }
  const resolved = (t, mode, chain = []) => {
    const next = target(t, mode)
    if (!next) return raw(t, mode)
    const seen = [...chain, t.name]
    if (seen.includes(next.name)) {
      throw new Error(`alias cycle: ${[...seen.slice(seen.indexOf(next.name)), next.name].join(' -> ')}`)
    }
    return resolved(next, mode, seen)
  }
  // The token at the end of an alias chain in one mode.
  const final = (t, mode) => {
    let cur = t
    for (let i = 0; i < 64; i++) {
      const next = target(cur, mode)
      if (!next) return cur
      cur = next
    }
    return cur
  }
  // A token's own type, else what its alias points at. A 2025.10 token then
  // takes its group's type and is never guessed from its value (the spec
  // forbids it); only a token in the old dialect falls back to a guess.
  const typeOf = (t, depth = 0) => {
    if (t.type) return t.type
    const next = target(t, 'default')
    if (next && depth < 32) return typeOf(next, depth + 1)
    if (t.strict) return t.groupType
    return inferType(resolved(t, 'default'), t.path[0])
  }
  const model = { tokens, byName, modes, defaultMode, modeLabel, raw, target, resolved, final, typeOf }

  // Check every token, naming it: every mode must resolve, a reference inside
  // a composite must point at a token, every string must be safe in CSS and
  // every value one CSS can write, a contrast pair must point at a real token,
  // and no two tokens may claim the same CSS variable.
  const owner = new Map()
  for (const t of tokens) {
    let ok = true
    for (const mode of modes) {
      try {
        resolved(t, mode)
      } catch (err) {
        report(t.name, err.message)
        ok = false
        continue
      }
      for (const ref of nestedRefs(raw(t, mode))) {
        if (byName.has(aliasPath(ref))) continue
        report(t.name, `reference ${ref} points at a token that does not exist`)
        ok = false
      }
      const own = [...stringLeaves(raw(t, mode))]
      const css = mode === 'default' ? t.css : t.cssModes?.[mode]
      if (typeof css === 'string') own.push(['$extensions.massimo.css', css])
      for (const [where, text] of own) {
        const why = unsafeCss(text)
        if (!why) continue
        report(t.name, `${where ? `${where} ` : ''}${JSON.stringify(text)} ${why}`)
        ok = false
      }
      // A 2025.10 token's value must be valid for its type.
      if (t.strict && !isAlias(raw(t, mode))) {
        const type = typeOf(t)
        const why = type ? checkValue(type, raw(t, mode)) : 'has no $type, and no group above it sets one'
        if (why) {
          report(t.name, `${mode === 'default' ? '' : `in ${modeLabel(mode)}, `}${type ? `the ${type} ` : ''}${why}`)
          ok = false
          continue
        }
      }
      if (t.cssOnly && typeof raw(t, mode) !== 'string') {
        report(t.name, 'a CSS-only value must be a string of CSS')
        ok = false
        continue
      }
      if (!ok) continue
      try {
        declarations(model, t, mode, false)
      } catch (err) {
        report(t.name, err.message)
        ok = false
      }
    }
    if (t.on && !byName.has(t.on)) report(t.name, `"on" points at ${t.on}, which is not a token`)
    if (!ok) continue
    // A reference and its target must agree on the type.
    const next = target(t, 'default')
    const own = t.type ?? (t.strict && !next ? t.groupType : null)
    if (t.strict && next && t.type && typeOf(next) && typeOf(next) !== t.type) {
      report(t.name, `is a ${t.type} but points at ${next.name}, a ${typeOf(next)}`)
      continue
    }
    if (t.strict && !own && !next && !t.cssOnly) continue
    for (const name of cssNames(model, t)) {
      const other = owner.get(name)
      if (other) report(t.name, `${other} and ${t.name} both map to the CSS variable ${name}; give one of them its own $extensions.massimo.cssVar`)
      else owner.set(name, t.name)
    }
    const v = resolved(t, 'default')
    const type = typeOf(t)
    if ((type === 'strokeStyle' && v && typeof v === 'object') || (type === 'border' && v?.style && typeof v.style === 'object')) {
      report(t.name, 'CSS has no dash pattern for borders, so the CSS outputs use dashed', 'warning')
    }
  }
  if (problems.some((p) => p.level === 'error')) throw new TokenProblems(problems)
  model.problems = problems
  return model
}

// Every "{path}" reference inside a composite value (not the value itself).
function* nestedRefs(v, top = true) {
  if (isAlias(v)) {
    if (!top) yield v
    return
  }
  if (Array.isArray(v)) for (const x of v) yield* nestedRefs(x, false)
  else if (v && typeof v === 'object') for (const x of Object.values(v)) yield* nestedRefs(x, false)
}

// The CSS variables a token owns: its own, plus one per part of a typography
// composite, since letter-spacing has no place in the `font` shorthand and
// Tailwind reads the parts one by one.
function cssNames(model, t) {
  if (model.typeOf(t) !== 'typography') return [t.cssVar]
  return [t.cssVar, ...TYPOGRAPHY_PARTS.map(([, css]) => `${t.cssVar}-${css}`)]
}

// The typography parts a token's value has, as [key, css name, part type].
function typographyParts(model, t) {
  const v = model.resolved(t, 'default')
  return TYPOGRAPHY_PARTS.filter(([key]) => v && typeof v === 'object' && v[key] !== undefined)
}

// A token's declarations in one mode, as [css variable, value] pairs. Linked
// output keeps aliases as var() so the theme cascades through them; literal
// output resolves every reference, for mockups, JSON and contrast.
function declarations(model, t, mode, linked) {
  let depth = 0
  const ref = (alias) => {
    const next = model.byName.get(aliasPath(alias))
    if (!next) throw new Error(`reference ${alias} points at a token that does not exist`)
    if (linked) return `var(${next.cssVar})`
    if (++depth > 32) throw new Error(`reference ${alias} goes round in a cycle`)
    return cssText(model.typeOf(next), model.resolved(next, mode), ref)
  }
  const type = model.typeOf(t)
  const next = linked ? model.target(t, mode) : null
  const value = linked ? model.raw(t, mode) : model.resolved(t, mode)
  // A value the spec cannot hold exactly keeps its exact CSS beside it.
  const cssOf = (x) => (mode !== 'default' && (mode in (x.cssModes ?? {}) || mode in x.modes) ? x.cssModes?.[mode] ?? null : x.css ?? null)
  const owner = linked ? t : model.final(t, mode)
  // A reference with CSS of its own wraps its target (rgb(var(--ink-900))
  // over a channel triplet): linked, that CSS is the value; as a literal,
  // the colour, not the target's channels.
  const own = isAlias(model.raw(t, mode)) ? cssOf(t) : null
  const css = linked ? (next ? own : cssOf(t)) : own !== null ? null : cssOf(owner)
  const out = [[t.cssVar, linked && next ? css ?? `var(${next.cssVar})` : css ?? cssText(type, value, ref)]]
  if (type === 'typography') {
    for (const [key, part, partType] of typographyParts(model, t)) {
      out.push([`${t.cssVar}-${part}`, next ? `var(${next.cssVar}-${part})` : cssText(partType, value[key], ref)])
    }
  }
  return out
}

const literal = (model, t, mode) => declarations(model, t, mode, false)[0][1]

// ── Loading tokens: tokens.json, or a draft from the style files ───────────

// The style files' custom properties as a token document in the dialect
// before 0.2.0, which is what the kit and preview fall back to before there
// is a token set, and what extract types and writes as 2025.10. A channel
// triplet keeps its channels here, so mockups read it as the product does.
function extractDraft(root, config, all = null) {
  const files = expandGlobs(root, config.tokens.styleFiles, [], config.ignore, all)
  const { tokens, count } = readCss(root, files)
  const byKey = new Map(tokens.map((t) => [t.path.join('.'), t]))
  // Types: literals infer from the value, aliases borrow from what they point at.
  const typeOfNode = (key, depth = 0) => {
    const t = byKey.get(key)
    if (!t) return 'string'
    if (t.type) return t.type
    if (isAlias(t.value)) return depth > 8 ? 'string' : typeOfNode(aliasPath(t.value), depth + 1)
    return inferType(t.value, key.split('.')[0])
  }
  const doc = { $description: `Draft extracted by massimo tokens extract from ${files.join(', ') || 'no style files'}. Review it, then save it as tokens.json.` }
  const groups = {}
  for (const t of tokens) (groups[t.path[0]] ??= []).push(t)
  for (const group of GROUP_ORDER) {
    if (!groups[group]) continue
    doc[group] = {}
    for (const t of groups[group]) {
      const key = t.path.join('.')
      const ext = {}
      if (`--${t.path.join('-')}` !== t.cssVar) ext.cssVar = t.cssVar
      const modes = Object.keys(t.modes)
      if (modes.length > 0) {
        const order = modes.sort((a, b) => (a === 'dark' ? -1 : b === 'dark' ? 1 : compare(a, b)))
        ext.modes = Object.fromEntries(order.map((m) => [m, t.cssModes?.[m] ?? t.modes[m]]))
      }
      const out = { $type: typeOfNode(key), $value: t.css ?? t.value }
      if (Object.keys(ext).length > 0) out.$extensions = { massimo: ext }
      doc[group][t.path[1]] = out
    }
  }
  return { doc, files, count, tokens }
}

// Readers' tokens (CSS text, types where the source gave them) as typed
// 2025.10 tokens, with the losses to report. A value whose exact CSS differs
// from what it converts to (a channel triplet) keeps that CSS beside it.
function draftFrom(found, config) {
  const tokens = found.map((t) => ({
    path: t.path,
    name: t.path.join('.'),
    type: t.type ?? null,
    value: t.value,
    modes: { ...t.modes },
    description: t.description ?? '',
    cssVar: t.cssVar ?? cssVarFor(t.path.filter((p) => p !== '$root')),
    on: t.contrast?.on ?? null,
    use: t.contrast?.use ?? null,
    contrast: CONTRAST_USES[t.contrast?.use] ?? 4.5,
    collection: null,
    extensions: {},
    deprecated: null,
  }))
  const legacy = buildModel(tokens, config)
  const { tokens: typed, losses } = typedFromLegacy(legacy.tokens, legacy.typeOf)
  typed.forEach((t, i) => {
    const source = found[i]
    if (t.cssOnly) return
    if (source.css) t.css = source.css
    if (source.cssModes) t.cssModes = { ...t.cssModes, ...source.cssModes }
  })
  return { tokens: typed, losses, defaultMode: legacy.defaultMode }
}

// Every place the config names where the repo keeps design values, read.
function readSources(root, config) {
  const sources = []
  const styleFiles = expandGlobs(root, config.tokens.styleFiles, [], config.ignore)
  if (styleFiles.length > 0) sources.push({ kind: 'css', ...readCss(root, styleFiles) })
  if (config.tokens.tailwindConfig) sources.push({ kind: 'tailwind', ...readTailwindConfig(root, config.tokens.tailwindConfig) })
  for (const file of expandGlobs(root, config.tokens.themeFiles ?? [], [], config.ignore)) sources.push({ kind: 'theme', ...readThemeObject(root, file) })
  for (const file of expandGlobs(root, config.tokens.importFiles ?? [], [], config.ignore)) {
    const notes = []
    const raw = readJsonFile(root, file)
    let tokens
    if (isTokensStudio(raw)) tokens = flattenDtcg(fromTokensStudio(raw, notes, file))
    else if (formatOf(raw) !== null || !looksLegacyDoc(raw)) tokens = flattenFormat(expandDocument(raw, notes), notes)
    else tokens = flattenDtcg(raw)
    sources.push({
      kind: 'tokens',
      tokens: tokens.map((t) => ({ path: t.path, type: t.type ?? t.groupType ?? null, value: t.value, modes: { ...t.modes }, cssVar: null, description: t.description, source: file })),
      notes: notes.map((n) => (typeof n === 'string' ? n : `${file}: ${n.path}: ${n.message}`)),
    })
  }
  if (config.tokens.figmaExport) sources.push({ kind: 'figma', ...readFigmaExport(root, config.tokens.figmaExport) })
  return { sources, styleFiles }
}

const looksLegacyDoc = (doc) => JSON.stringify(doc).includes('"massimo":{"modes"') || /"\$value":\s*"#/.test(JSON.stringify(doc))

const FAMILY_TITLES = { color: 'Colour', typography: 'Typography', spacing: 'Spacing', radius: 'Radius', shadow: 'Shadow', border: 'Border', motion: 'Motion', 'z-index': 'Layers', opacity: 'Opacity', other: 'Other' }
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

// The draft's report: what each token is and where it came from, family by
// family, then the values not proposed, notes and conversion losses.
function draftReport({ sources, audit, report, outliers, notes, losses, count }) {
  const read = sources.map((s) => [...new Set(s.tokens.map((t) => t.source))].join(', ')).filter(Boolean)
  const lines = ['# Draft tokens', '']
  lines.push(`${count} tokens, read from ${read.length ? read.join(', ') : 'no source files'} and the code itself (${audit?.scannedFiles ?? 0} files audited). Nothing here is in use yet: review it family by family with the tokens skill.`, '')
  for (const family of [...FAMILIES, 'other']) {
    const rows = report.filter((r) => r.family === family)
    if (rows.length === 0) continue
    lines.push(`## ${FAMILY_TITLES[family]}`, '', '| Token | Value | From | Note |', '|---|---|---|---|')
    for (const r of rows) lines.push(`| \`${cell(r.token)}\` | ${cell(r.value)} | ${cell(r.from)} | ${cell(r.note)} |`)
    lines.push('')
  }
  if (outliers.length) {
    lines.push('## Not proposed', '', 'Values the code uses that did not become tokens: used once, off the grid, off a scale the sources already define, or only ever data. Replace each with a token in the tidy phase, or keep it with a reason.', '', '| Family | Value | Uses | Note |', '|---|---|---|---|')
    for (const o of outliers) lines.push(`| ${FAMILY_TITLES[o.family] ?? o.family} | ${cell(o.value)} | ${o.count} | ${cell(o.note)} |`)
    lines.push('')
  }
  if (losses.length) {
    lines.push('## What did not convert exactly', '')
    for (const l of losses) lines.push(`- \`${l.token}\` (${l.kind}): ${l.detail}`)
    lines.push('')
  }
  if (notes.length) {
    lines.push('## Notes', '')
    for (const n of notes) lines.push(`- ${n}`)
    lines.push('')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

// The token set, with the problems found reading it (passed on to buildModel)
// and which dialect it is in: '2025.10' (a resolver document, or one token
// file with massimo's format version) or 'legacy' (what massimo wrote before
// 0.2.0, read as before so existing projects build unchanged).
function loadTokens(root, config, { draftOk = false, all = null } = {}) {
  const problems = []
  const read = readTokenSource(root, config, problems)
  if (read) return { ...read, origin: 'tokens' }
  if (!draftOk) return null
  const draft = extractDraft(root, config, all)
  return { tokens: flattenDtcg(draft.doc, problems), problems, origin: draft.count > 0 ? 'draft' : 'none', format: 'legacy', files: draft.files }
}

