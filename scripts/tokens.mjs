import { compare, expandGlobs } from './lib/glob.mjs'
import { fail, loadConfig, parseArgs, readJson, rel } from './lib/project.mjs'
import { aliasPath, flattenDtcg, isAlias, parseCustomProperties, splitVarName } from './lib/source.mjs'

const HEADER = 'GENERATED by massimo tokens — edit tokens.json, then run node design-system/scripts/tokens.mjs build'
const GROUP_ORDER = ['color', 'spacing', 'radius', 'font', 'text', 'shadow', 'size', 'other']
const FORMATS = ['css', 'tailwind4', 'tailwind3', 'scss', 'json', 'ts']

// ── Small helpers ───────────────────────────────────────────────────────────

const natural = (a, b) => {
  const pa = a.split(/(\d+)/)
  const pb = b.split(/(\d+)/)
  for (let i = 0; i < Math.min(pa.length, pb.length); i++) {
    if (pa[i] === pb[i]) continue
    if (i % 2 === 1) return Number(pa[i]) - Number(pb[i])
    return compare(pa[i], pb[i])
  }
  return pa.length - pb.length
}

const titleCase = (s) => s.charAt(0).toUpperCase() + s.slice(1)
const round = (n, places = 6) => Number(n.toFixed(places))
const writeText = (path, text) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
}
const jsonText = (value) => `${JSON.stringify(value, null, 2)}\n`

const LENGTH = /^-?(?:\d+\.?\d*|\.\d+)(?:px|rem|em)$/
const GENERIC_FAMILY = /^(?:serif|sans-serif|monospace|cursive|fantasy|system-ui|ui-[a-z-]+)$/i

function inferType(value, group = '') {
  if (typeof value === 'number') return 'number'
  if (typeof value !== 'string') return 'string'
  const v = value.trim()
  if (parseColor(v)) return 'color'
  if (LENGTH.test(v)) return 'dimension'
  if (/^-?(?:\d+\.?\d*|\.\d+)$/.test(v)) return 'number'
  if (group === 'font' && (v.includes(',') || /^['"]/.test(v) || GENERIC_FAMILY.test(v))) return 'fontFamily'
  return 'string'
}

// ── Values to CSS and to Figma ──────────────────────────────────────────────

function dimensionText(v) {
  if (typeof v === 'number') return `${v}px`
  if (v && typeof v === 'object' && 'value' in v) return `${v.value}${v.unit ?? 'px'}`
  return String(v)
}

const quoteFamily = (name) => (/^[\w-]+$/.test(name) || GENERIC_FAMILY.test(name) ? name : `"${name}"`)

// A resolved DTCG value as CSS text.
function cssText(type, v) {
  if (typeof v === 'string') return v.trim()
  if (typeof v === 'number') return type === 'dimension' ? `${v}px` : String(v)
  if (Array.isArray(v)) {
    if (type === 'cubicBezier') return `cubic-bezier(${v.join(', ')})`
    if (type === 'fontFamily') return v.map(quoteFamily).join(', ')
    if (type === 'shadow') return v.map((s) => cssText('shadow', s)).join(', ')
    return v.join(', ')
  }
  if (v && typeof v === 'object') {
    if (type === 'color' || 'colorSpace' in v) {
      if (v.colorSpace === 'srgb' && Array.isArray(v.components)) {
        return toHex({ r: v.components[0], g: v.components[1], b: v.components[2], a: v.alpha ?? 1 })
      }
      return String(v.hex ?? JSON.stringify(v))
    }
    if (type === 'shadow' || 'offsetX' in v) {
      const color = cssText('color', v.color ?? '#000000')
      const parts = [v.offsetX, v.offsetY, v.blur, v.spread].filter((x) => x !== undefined).map(dimensionText)
      return `${v.inset ? 'inset ' : ''}${parts.join(' ')} ${color}`
    }
    if ('value' in v) return dimensionText(v)
  }
  return String(v)
}

// ── The token model ─────────────────────────────────────────────────────────

function buildModel(tokens) {
  const byName = new Map(tokens.map((t) => [t.name, t]))
  const modeNames = new Set()
  for (const t of tokens) for (const m of Object.keys(t.modes)) modeNames.add(m)
  const modes = ['default', ...[...modeNames].sort((a, b) => (a === 'dark' ? -1 : b === 'dark' ? 1 : compare(a, b)))]

  const raw = (t, mode) => (mode === 'default' || !(mode in t.modes) ? t.value : t.modes[mode])
  const target = (t, mode) => {
    const v = raw(t, mode)
    if (!isAlias(v)) return null
    const next = byName.get(aliasPath(v))
    if (!next) throw new Error(`${t.name}: alias ${v} points at a token that does not exist`)
    return next
  }
  const resolved = (t, mode, chain = []) => {
    const next = target(t, mode)
    if (!next) return raw(t, mode)
    const seen = [...chain, t.name]
    if (seen.includes(next.name)) {
      throw new Error(`Alias cycle: ${[...seen.slice(seen.indexOf(next.name)), next.name].join(' -> ')}`)
    }
    return resolved(next, mode, seen)
  }
  const typeOf = (t) => t.type ?? inferType(resolved(t, 'default'), t.path[0])
  const model = { tokens, byName, modes, raw, target, resolved, typeOf }

  // Fail early, naming the chain: every token in every mode must resolve, and
  // every contrast pair must point at a real token.
  for (const t of tokens) {
    for (const mode of modes) resolved(t, mode)
    if (t.on && !byName.has(t.on)) throw new Error(`${t.name}: "on" points at ${t.on}, which is not a token`)
  }
  return model
}

// The CSS value a token declares in one mode: var(--target) for an alias, else the literal.
function declared(model, t, mode) {
  const next = model.target(t, mode)
  return next ? `var(${next.cssVar})` : cssText(model.typeOf(t), model.raw(t, mode))
}

const literal = (model, t, mode) => cssText(model.typeOf(t), model.resolved(t, mode))

// ── Loading tokens: tokens.json, or a draft from the style files ───────────

function extractDraft(root, config, all = null) {
  const files = expandGlobs(root, config.tokens.styleFiles, [], config.ignore, all)
  const entries = new Map()
  for (const file of files) {
    for (const p of parseCustomProperties(readFileSync(join(root, file), 'utf8'), file)) {
      if (p.scope === 'local' || p.name.startsWith('--tw-')) continue
      const e = entries.get(p.name) ?? { default: undefined, modes: {} }
      if (p.mode === 'default') e.default = p.value
      else e.modes[p.mode] = p.value
      entries.set(p.name, e)
    }
  }
  const idOf = new Map()
  for (const name of entries.keys()) {
    const { group, rest } = splitVarName(name)
    idOf.set(name, { group, token: rest || 'base' })
  }
  const aliasOf = (value) => {
    const m = /^var\(\s*(--[\w-]+)\s*\)$/.exec(value)
    const id = m && idOf.get(m[1])
    return id ? `{${id.group}.${id.token}}` : value
  }
  const groups = {}
  const typed = new Map()
  for (const name of [...entries.keys()].sort(natural)) {
    const { group, token } = idOf.get(name)
    const e = entries.get(name)
    const first = e.default ?? Object.values(e.modes)[0]
    const node = { $value: aliasOf(first) }
    const ext = {}
    if (`--${group}-${token}` !== name) ext.cssVar = name
    const modes = {}
    // A mode that repeats the default adds nothing; a token with no default
    // takes its first mode's value as the default.
    const extra = e.default !== undefined ? Object.entries(e.modes) : Object.entries(e.modes).slice(1)
    for (const [mode, v] of extra) if (aliasOf(v) !== node.$value) modes[mode] = aliasOf(v)
    if (Object.keys(modes).length > 0) ext.modes = Object.fromEntries(Object.keys(modes).sort((a, b) => (a === 'dark' ? -1 : b === 'dark' ? 1 : compare(a, b))).map((k) => [k, modes[k]]))
    node.__ext = ext
    ;(groups[group] ??= {})[token] = node
    typed.set(`${group}.${token}`, node)
  }
  // Types: literals infer from the value, aliases borrow from what they point at.
  const typeOfNode = (key, depth = 0) => {
    const node = typed.get(key)
    if (!node) return 'string'
    if (isAlias(node.$value)) return depth > 8 ? 'string' : typeOfNode(aliasPath(node.$value), depth + 1)
    return inferType(node.$value, key.split('.')[0])
  }
  const doc = { $description: `Draft extracted by massimo tokens extract from ${files.join(', ') || 'no style files'}. Review it, then save it as tokens.json.` }
  for (const group of GROUP_ORDER) {
    if (!groups[group]) continue
    doc[group] = {}
    for (const [token, node] of Object.entries(groups[group])) {
      const out = { $type: typeOfNode(`${group}.${token}`), $value: node.$value }
      if (Object.keys(node.__ext).length > 0) out.$extensions = { massimo: node.__ext }
      doc[group][token] = out
    }
  }
  return { doc, files, count: entries.size }
}

function loadTokens(root, config, { draftOk = false, all = null } = {}) {
  const path = join(root, config.tokens.source)
  if (existsSync(path)) {
    return { tokens: flattenDtcg(readJson(path)), origin: 'tokens.json', files: [config.tokens.source] }
  }
  if (!draftOk) return null
  const draft = extractDraft(root, config, all)
  return { tokens: flattenDtcg(draft.doc), origin: 'draft', files: draft.files }
}

// ── Output formats ──────────────────────────────────────────────────────────

const cssBlock = (selector, lines, indent = '') => [`${indent}${selector} {`, ...lines.map((l) => (l ? `${indent}  ${l}` : l)), `${indent}}`]

// Declarations for one mode: tokens with their own value in that mode.
function modeLines(model, mode, valueOf) {
  const lines = []
  for (const t of model.tokens) {
    if (mode !== 'default' && !(mode in t.modes)) continue
    lines.push(`${t.cssVar}: ${valueOf(t, mode)};`)
  }
  return lines
}

function modeBlocks(model, darkSelector, darkMedia, valueOf) {
  const out = []
  const dark = modeLines(model, 'dark', valueOf)
  if (dark.length > 0) {
    out.push('', ...cssBlock(darkSelector, dark))
    if (darkMedia) {
      out.push('', '@media (prefers-color-scheme: dark) {', ...cssBlock(':root:not([data-theme="light"])', dark, '  '), '}')
    }
  }
  for (const mode of model.modes.filter((m) => m !== 'default' && m !== 'dark')) {
    out.push('', ...cssBlock(`[data-theme="${mode}"]`, modeLines(model, mode, valueOf)))
  }
  return out
}

function buildCss(model, config) {
  const root = []
  let group = null
  for (const t of model.tokens) {
    if (t.path[0] !== group) {
      group = t.path[0]
      if (root.length > 0) root.push('')
      root.push(`/* ${group} */`)
    }
    root.push(`${t.cssVar}: ${declared(model, t, 'default')};`)
  }
  const out = [`/* ${HEADER} */`, '', ...cssBlock(':root', root)]
  out.push(...modeBlocks(model, config.tokens.darkSelector, config.tokens.darkMedia, (t, mode) => declared(model, t, mode)))
  return `${out.join('\n')}\n`
}

// Where a token lands in Tailwind: a theme section and a key path inside it.
function tailwindTarget(model, t) {
  const type = model.typeOf(t)
  const [first, ...rest] = t.path
  if (type === 'color') return { section: 'colors', keys: first === 'color' ? rest : t.path }
  if (first === 'spacing') return { section: 'spacing', keys: rest }
  if (first === 'radius') return { section: 'borderRadius', keys: rest }
  if (type === 'fontFamily') return { section: 'fontFamily', keys: first === 'font' ? rest : t.path }
  if (first === 'text') return { section: 'fontSize', keys: rest }
  if (first === 'font' && /^sizes?$/.test(rest[0] ?? '')) return { section: 'fontSize', keys: rest.slice(1) }
  if (first === 'shadow' || type === 'shadow') return { section: 'boxShadow', keys: first === 'shadow' ? rest : t.path }
  return null
}

const TAILWIND4_PREFIX = { colors: '--color', spacing: '--spacing', borderRadius: '--radius', fontFamily: '--font', fontSize: '--text', boxShadow: '--shadow' }

function buildTailwind4(model) {
  const lines = []
  for (const t of model.tokens) {
    const hit = tailwindTarget(model, t)
    if (!hit || (hit.keys.length === 0 && hit.section !== 'spacing')) continue
    const name = [TAILWIND4_PREFIX[hit.section], ...hit.keys].join('-')
    lines.push(`${name}: var(${t.cssVar});`)
  }
  return [
    `/* ${HEADER} */`,
    '/* Utilities read these through var(), so the values (and the dark mode) come from the css output. */',
    '/* A token whose css variable has the same name as its theme variable maps to itself; that is intended, not a loop. */',
    '',
    ...cssBlock('@theme inline', lines),
    '',
  ].join('\n')
}

const IDENT = /^[A-Za-z_$][\w$]*$/

function setNested(obj, keys, value) {
  let cur = obj
  keys.forEach((key, i) => {
    const last = i === keys.length - 1
    if (last) {
      if (cur[key] && typeof cur[key] === 'object') cur[key].DEFAULT = value
      else cur[key] = value
    } else {
      if (typeof cur[key] === 'string') cur[key] = { DEFAULT: cur[key] }
      cur[key] ??= {}
      cur = cur[key]
    }
  })
}

function objectLiteral(obj, depth = 0) {
  const pad = '  '.repeat(depth + 1)
  const lines = Object.keys(obj).map((k) => {
    const key = IDENT.test(k) ? k : `'${k}'`
    const v = obj[k]
    return `${pad}${key}: ${typeof v === 'string' ? `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'` : objectLiteral(v, depth + 1)},`
  })
  return `{\n${lines.join('\n')}\n${'  '.repeat(depth)}}`
}

function buildTailwind3(model) {
  const theme = { colors: {}, spacing: {}, borderRadius: {}, fontFamily: {}, fontSize: {}, boxShadow: {} }
  for (const t of model.tokens) {
    const hit = tailwindTarget(model, t)
    if (!hit) continue
    setNested(theme[hit.section], hit.keys.length > 0 ? hit.keys : ['DEFAULT'], `var(${t.cssVar})`)
  }
  for (const k of Object.keys(theme)) if (Object.keys(theme[k]).length === 0) delete theme[k]
  return [
    `// ${HEADER}`,
    "// Use it as: module.exports = { theme: { extend: require('./tokens.tailwind.cjs') } }",
    '// Colours are var() references, so opacity modifiers (bg-primary/50) need channel-form variables.',
    `module.exports = ${objectLiteral(theme)}`,
    '',
  ].join('\n')
}

function buildScss(model) {
  const lines = [`// ${HEADER}`, '']
  let group = null
  for (const t of model.tokens) {
    if (t.path[0] !== group) {
      if (group !== null) lines.push('')
      group = t.path[0]
    }
    lines.push(`$${t.cssVar.replace(/^--/, '')}: var(${t.cssVar});`)
  }
  return `${lines.join('\n')}\n`
}

function buildJson(model) {
  const tokens = {}
  for (const t of model.tokens) {
    const values = {}
    for (const mode of model.modes) values[mode] = literal(model, t, mode)
    tokens[t.name] = { type: model.typeOf(t), cssVar: t.cssVar, values }
  }
  return jsonText({ $comment: HEADER, generatedBy: 'massimo tokens', modes: model.modes, tokens })
}

function buildTs(model) {
  const tree = {}
  for (const t of model.tokens) setNested(tree, t.path, `var(${t.cssVar})`)
  return [
    `// ${HEADER}`,
    '// Each leaf is the token as a CSS var() reference, so it follows the active theme.',
    `export const tokens = ${objectLiteral(tree)} as const`,
    '',
  ].join('\n')
}

// ── Figma variables ─────────────────────────────────────────────────────────

const figmaMode = (mode) => (mode === 'default' ? 'Light' : titleCase(mode))

function figmaValue(model, t, mode, type) {
  const next = model.target(t, mode)
  if (next) return { alias: next.path.join('/') }
  const v = model.raw(t, mode)
  const css = cssText(model.typeOf(t), v)
  if (type === 'COLOR') {
    const c = parseColor(css)
    return { r: round(c.r), g: round(c.g), b: round(c.b), a: round(c.a) }
  }
  if (type === 'FLOAT') {
    const m = /^(-?[\d.]+)(px|rem|em)?$/.exec(css)
    return round(m[2] === 'rem' || m[2] === 'em' ? parseFloat(m[1]) * 16 : parseFloat(m[1]), 4)
  }
  return css
}

function figmaType(model, t) {
  const type = model.typeOf(t)
  const all = model.modes.map((m) => cssText(type, model.resolved(t, m)))
  if (type === 'color' && all.every((v) => parseColor(v))) return 'COLOR'
  if (['dimension', 'number', 'fontWeight', 'duration'].includes(type) && all.every((v) => /^-?[\d.]+(px|rem|em)?$/.test(v))) return 'FLOAT'
  return 'STRING'
}

function buildFigma(model) {
  const collections = new Map()
  for (const t of model.tokens) {
    const type = figmaType(model, t)
    const name = t.collection ?? (isAlias(t.value) ? 'Semantic' : 'Primitives')
    const values = {}
    for (const mode of model.modes) values[figmaMode(mode)] = figmaValue(model, t, mode, type)
    if (!collections.has(name)) collections.set(name, [])
    collections.get(name).push({
      name: t.path.join('/'),
      type,
      values,
      description: t.description,
      codeSyntax: { WEB: `var(${t.cssVar})` },
    })
  }
  const order = ['Primitives', 'Semantic', ...[...collections.keys()].filter((k) => k !== 'Primitives' && k !== 'Semantic').sort(compare)]
  return jsonText({
    $comment: HEADER,
    generatedBy: 'massimo tokens',
    collections: order.filter((n) => collections.has(n)).map((name) => ({ name, modes: model.modes.map(figmaMode), variables: collections.get(name) })),
  })
}

// ── The kit: literal values for mockups ─────────────────────────────────────

const BODY_FONT = ['--font-sans', '--font-body', '--font-family', '--font-base']
const BODY_COLOR = ['--color-base-content', '--color-fg', '--color-foreground', '--color-text', '--color-text-default', '--color-fg-default', '--color-content', '--color-on-surface']
const BODY_BG = ['--color-base-100', '--color-bg', '--color-background', '--color-bg-default', '--color-surface', '--color-surface-default']

function buildKit(model, origin, files) {
  const present = new Set(model.tokens.map((t) => t.cssVar))
  const pick = (names) => names.find((n) => present.has(n))
  const font = pick(BODY_FONT)
  const fg = pick(BODY_COLOR)
  const bg = pick(BODY_BG)
  const source = origin === 'tokens.json' ? 'Source: tokens.json.' : `Source: custom properties extracted from ${files.join(', ') || 'the style files'} (no tokens.json yet).`
  const valueOf = (t, mode) => literal(model, t, mode)
  const out = [`/* ${HEADER} */`, `/* ${source} Link this file from mockups so they look like the product. */`, '']
  out.push(...cssBlock(':root', ['color-scheme: light;', ...modeLines(model, 'default', valueOf)]))
  const dark = modeLines(model, 'dark', valueOf)
  out.push('', ...cssBlock('[data-theme="dark"]', ['color-scheme: dark;', ...dark]))
  if (dark.length > 0) {
    out.push('', '@media (prefers-color-scheme: dark) {', ...cssBlock(':root:not([data-theme="light"])', ['color-scheme: dark;', ...dark], '  '), '}')
  }
  for (const mode of model.modes.filter((m) => m !== 'default' && m !== 'dark')) {
    out.push('', ...cssBlock(`[data-theme="${mode}"]`, modeLines(model, mode, valueOf)))
  }
  out.push('', '*, *::before, *::after {', '  box-sizing: border-box;', '}')
  const body = ['margin: 0;', `font-family: ${font ? `var(${font})` : 'system-ui, sans-serif'};`]
  if (fg) body.push(`color: var(${fg});`)
  if (bg) body.push(`background: var(${bg});`)
  out.push('', ...cssBlock('body', body))
  return `${out.join('\n')}\n`
}

// ── Contrast ────────────────────────────────────────────────────────────────

function contrastChecks(model) {
  const results = []
  for (const t of model.tokens) {
    if (!t.on) continue
    const bgToken = model.byName.get(t.on)
    for (const mode of model.modes) {
      const fg = parseColor(literal(model, t, mode))
      const bg = parseColor(literal(model, bgToken, mode))
      if (!fg || !bg) continue
      const ratio = contrastRatio(fg, bg)
      results.push({ token: t.name, on: t.on, mode, ratio, needs: t.contrast, pass: ratio >= t.contrast })
    }
  }
  return results
}

