const natural = (a, b) => {
  const pa = a.split(/(\d+)/)
  const pb = b.split(/(\d+)/)
  for (let i = 0; i < Math.min(pa.length, pb.length); i++) {
    if (pa[i] === pb[i]) continue
    if (i % 2 === 1) return Number(pa[i]) - Number(pb[i])
    return compare(pa[i], pb[i])
  }
  return pa.length - pb.length
}

