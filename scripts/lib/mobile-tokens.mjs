// What the mobile token outputs share: which tokens each one can carry, as
// plain entries (a group, a member name per language, and the value in
// points, milliseconds and colour components), what is not carried over and
// why, and the header and ownership rules every mobile file follows.
//
// Builders read values through the model (`model.resolved`), never the CSS
// text, so an output is the token set's value, not a stylesheet's.

import { parseColor } from './color.mjs'
import { KOTLIN_RESERVED, SWIFT_RESERVED, collisions, groupOf, memberName } from './mobile-names.mjs'
import { colorValue, deepResolve, lengthOf, millisecondsOf } from './mobile-units.mjs'

export const MOBILE_FORMATS = ['swift', 'xcassets', 'compose', 'android-xml']
export const PLATFORM_OF_FORMAT = { swift: 'ios', xcassets: 'ios', compose: 'android', 'android-xml': 'android' }

// The line after the header in every mobile file: its format, which changes
// only when what massimo writes there changes shape.
export const MOBILE_FORMAT_LINE = 'massimo mobile output, format 1'

// Whether a file's head says massimo wrote it.
export function hasMassimoHeader(text) {
  const head = String(text).split('\n').slice(0, 4).join('\n')
  return /Generated by massimo tokens\b/.test(head)
}

const SYSTEM_FAMILIES = /^(?:system-ui|-apple-system|blinkmacsystemfont|sf pro(?: text| display)?|\.sf\b.*|sans-serif|ui-sans-serif)$/i
const ROBOTO = /^roboto$/i

// CSS's generic families that name a design of the system font: SwiftUI's
// Font.Design, and Compose's FontFamily where Android has one.
const GENERIC_DESIGNS = new Map([['ui-monospace', 'monospaced'], ['monospace', 'monospaced'], ['ui-serif', 'serif'], ['serif', 'serif'], ['ui-rounded', 'rounded'], ['cursive', 'cursive'], ['fantasy', 'fantasy']])

// A family list as its first family, whether that is the system font, and
// the system font's design a generic family names (monospaced, serif,
// rounded), which is the system font too, with nothing to bundle.
export function familyOf(value) {
  const list = Array.isArray(value) ? value : String(value ?? '').split(',')
  const first = String(list[0] ?? '').trim().replace(/^(['"])(.*)\1$/, '$2')
  const design = GENERIC_DESIGNS.get(first.toLowerCase()) ?? null
  return { name: first, system: Boolean(design) || SYSTEM_FAMILIES.test(first), roboto: ROBOTO.test(first), design }
}

const WEIGHT_WORDS = { thin: 100, hairline: 100, 'extra-light': 200, 'ultra-light': 200, light: 300, normal: 400, regular: 400, book: 400, medium: 500, 'semi-bold': 600, 'demi-bold': 600, bold: 700, 'extra-bold': 800, 'ultra-bold': 800, black: 900, heavy: 900, 'extra-black': 950, 'ultra-black': 950 }
export const weightOf = (v) => (typeof v === 'number' ? v : WEIGHT_WORDS[String(v).trim()] ?? (Number(v) || null))

// A token's value in one mode as a plain entry value, or { skip } with why it
// is not carried over. `type` is the model's type for the token.
function plainValue(model, t, type, mode, options) {
  const v = deepResolve(model, model.resolved(t, mode), mode)
  const len = (x) => lengthOf(x, options)
  switch (type) {
    case 'color': {
      const c = colorValue(v, parseColor)
      return c ? { color: c } : { skip: 'is not a colour these outputs can write' }
    }
    case 'dimension': {
      const l = len(v)
      return l.value === null ? { skip: l.why } : { points: l.value }
    }
    case 'number':
      return typeof v === 'number' ? { number: v } : { skip: 'is not a number' }
    case 'fontWeight': {
      const w = weightOf(v)
      return w ? { weight: w } : { skip: 'is not a font weight' }
    }
    case 'fontFamily':
      return { family: familyOf(v) }
    case 'duration': {
      const d = millisecondsOf(v)
      return d.value === null ? { skip: d.why } : { ms: d.value }
    }
    case 'cubicBezier':
      return Array.isArray(v) && v.length === 4 && v.every((n) => typeof n === 'number') ? { curve: v } : { skip: 'is not a cubic Bézier curve' }
    case 'typography': {
      if (!v || typeof v !== 'object') return { skip: 'is not a typography value' }
      const size = v.fontSize === undefined ? null : len(v.fontSize)
      if (!size || size.value === null) return { skip: `has no font size these outputs can write${size?.why ? ` (it ${size.why})` : ''}` }
      let lineHeight = null
      if (typeof v.lineHeight === 'number') lineHeight = Number((v.lineHeight * size.value).toFixed(4))
      else if (v.lineHeight !== undefined) lineHeight = len(v.lineHeight).value
      let tracking = null
      if (v.letterSpacing !== undefined) {
        const ls = v.letterSpacing
        tracking = ls && typeof ls === 'object' && ls.unit === 'em' ? Number((ls.value * size.value).toFixed(4)) : len(ls).value
      }
      return { text: { size: size.value, family: v.fontFamily === undefined ? null : familyOf(v.fontFamily), weight: v.fontWeight === undefined ? null : weightOf(v.fontWeight), lineHeight, tracking } }
    }
    case 'shadow': {
      const layers = [].concat(v)
      if (!layers.every((l) => l && typeof l === 'object' && 'offsetX' in l)) return { skip: 'is a shadow written as CSS text' }
      const out = []
      for (const l of layers) {
        const c = colorValue(l.color ?? '#000000', parseColor)
        const [x, y, blur, spread] = [l.offsetX, l.offsetY, l.blur ?? { value: 0, unit: 'px' }, l.spread ?? { value: 0, unit: 'px' }].map((d) => len(d).value)
        if (!c || [x, y, blur].some((n) => n === null)) return { skip: 'has a shadow layer these outputs cannot write' }
        out.push({ color: c, x, y, blur, spread: spread ?? 0, inset: Boolean(l.inset) })
      }
      return { shadow: out }
    }
    case 'border': {
      const width = len(v?.width).value
      const c = colorValue(v?.color, parseColor)
      if (width === null || !c) return { skip: 'is a border these outputs cannot write' }
      const style = typeof v.style === 'string' ? v.style : 'dashed'
      return { border: { width, color: c, style } }
    }
    case 'gradient': {
      const stops = [].concat(v).map((s) => ({ color: colorValue(s?.color, parseColor), position: typeof s?.position === 'number' ? s.position : null }))
      if (stops.some((s) => !s.color || s.position === null)) return { skip: 'is a gradient these outputs cannot write' }
      return { gradient: stops }
    }
    case 'transition':
      return { skip: 'is a transition, which has no single value on a phone: use its duration and curve tokens' }
    case 'strokeStyle':
      return { skip: 'is a stroke style on its own; a border carries solid or dashed' }
    case 'css':
      return { skip: 'is a CSS-only value' }
    default:
      return { skip: `is a ${type ?? 'value with no type'}, which these outputs do not write` }
  }
}

// Every token the mobile outputs may carry, as entries:
//   { t, group, swift, kotlin, type, value, dark, target, notes }
// in the token set's order. `target` is the token a colour alias ends at. `value` and `dark` are plain values (see
// plainValue); `dark` is set only for a colour that changes in dark mode.
// Tokens that cannot be carried are in `skipped` as { token, why }, and
// renames in `renamed`. Two tokens that would share a name are `collisions`.
export function mobileEntries(model, options) {
  const entries = []
  const skipped = []
  const renamed = []
  // The day value and the dark one. A set whose default mode is dark keeps
  // its light mode as the day value and its default as the dark one, so a
  // phone in light appearance never shows the dark colours.
  const labelled = (label) => model.modes.find((m) => m !== 'default' && model.modeLabel(m) === label) ?? null
  const darkDefault = model.modeLabel('default') === 'dark'
  const day = darkDefault ? labelled('light') ?? 'default' : 'default'
  const dark = darkDefault ? (day === 'default' ? null : 'default') : labelled('dark')
  const hasDark = dark !== null
  const otherModes = model.modes.filter((m) => m !== day && m !== dark)
  for (const t of model.tokens) {
    if (t.cssOnly) {
      skipped.push({ token: t.name, why: 'is a CSS-only value' })
      continue
    }
    const type = model.typeOf(t)
    const notes = []
    let value
    try {
      value = plainValue(model, t, type, day, options)
    } catch (err) {
      skipped.push({ token: t.name, why: err.message })
      continue
    }
    if (value.skip) {
      skipped.push({ token: t.name, why: value.skip })
      continue
    }
    let darkValue = null
    if (hasDark) {
      const d = plainValue(model, t, type, dark, options)
      if (!d.skip && JSON.stringify(d) !== JSON.stringify(value)) {
        if (type === 'color') darkValue = d
        else notes.push(`its ${model.modeLabel(dark)} value is not carried over: only colours change with the appearance on a phone`)
      }
    }
    if (typeof t.css === 'string' && t.css.trim()) notes.push(`its exact CSS (${t.css.trim()}) is the web's; the mobile outputs use its value`)
    for (const m of otherModes) {
      if (m in t.modes) notes.push(`its ${model.modeLabel(m)} value is not carried over: the mobile outputs hold the default and dark only`)
    }
    const group = groupOf(t.path, type).name
    const swift = memberName(t.path, type, SWIFT_RESERVED)
    const kotlin = memberName(t.path, type, KOTLIN_RESERVED)
    if (swift.renamed) renamed.push({ token: t.name, language: 'Swift', name: swift.name, why: swift.renamed })
    if (kotlin.renamed) renamed.push({ token: t.name, language: 'Kotlin', name: kotlin.name, why: kotlin.renamed })
    const end = type === 'color' ? model.final(t, day) : t
    entries.push({ t, group, swift: swift.name, kotlin: kotlin.name, type, value, dark: darkValue, target: end === t ? null : end, notes })
  }
  const clash = (lang) =>
    [...new Set(entries.map((e) => e.group))].flatMap((group) => collisions(entries.filter((e) => e.group === group).map((e) => ({ name: e[lang], token: e.t.name }))).map((c) => ({ ...c, group, language: lang === 'swift' ? 'Swift' : 'Kotlin' })))
  return { entries, skipped, renamed, collisions: [...clash('swift'), ...clash('kotlin')] }
}

// The groups in the order the code outputs write them.
export const GROUP_ORDER = ['Colors', 'Spacing', 'Radius', 'Sizes', 'Typography', 'Shadows', 'Borders', 'Gradients', 'Motion', 'Opacity', 'Layers', 'Numbers', 'Other']
export const groupRank = (g) => (GROUP_ORDER.includes(g) ? GROUP_ORDER.indexOf(g) : GROUP_ORDER.length)
