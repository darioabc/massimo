// adopt.mjs verify, accept, historical and retire --dry-run on a repo with
// its own setup: massimo's graph, story lane, audit and token inventory set
// beside what the repo's own tools wrote, each difference keyed so the
// ledger can accept it with a reason, and the dry run of a retirement that
// lists what goes and who still depends on it.

import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { after, test } from 'node:test'
import { workflowJob } from '../scripts/lib/inventory.mjs'
import { compareGraph, compareTokens, readGraphDoc, readIndexDoc, readTokenInventory, settle, storyPairs, storyRoutes, textTable } from '../scripts/lib/verify.mjs'
import { FIXTURES, SCRIPTS, readJson, scratch } from './helpers.mjs'

const ctx = scratch('legacy')
after(() => ctx.cleanup())
const env = { ...process.env, MASSIMO_TODAY: '2026-11-07' }
const script = (name, args = [], extra = {}) => spawnSync(process.execPath, [join(SCRIPTS, `${name}.mjs`), ...args, '--root', ctx.root], { encoding: 'utf8', env: { ...env, ...extra }, cwd: ctx.root })
const adopt = (...args) => script('adopt', args)
const project = join(ctx.root, 'design-system')
const ledger = () => readJson(project, 'adopt', 'ledger.json')
const write = (file, text) => writeFileSync(join(ctx.root, file), text)
// A row of a printed table, as its cells.
const cells = (text, label) => text.split('\n').map((l) => l.trim()).find((l) => l === label || l.startsWith(`${label}  `))?.split(/\s{2,}/) ?? null
const config = (change) => {
  const path = join(ctx.root, 'massimo.config.json')
  const c = JSON.parse(readFileSync(path, 'utf8'))
  change(c)
  writeFileSync(path, JSON.stringify(c, null, 2))
}

for (const step of [['init', ['--no-npm-scripts']], ['adopt', ['scan']], ['adopt', ['plan']], ['adopt', ['config', '--write']]]) {
  const r = script(...step)
  assert.equal(r.status, 0, `${step.join(' ')}: ${r.stderr}`)
}

