// detect.mjs says when a repo has something to adopt, in a short list the
// start skill reads, and says nothing new for a repo with nothing to adopt:
// not for a README that says "generated", a design.md with no tokens, or one
// stray header key.

import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { after, test } from 'node:test'
import { SCRIPTS, scratch } from './helpers.mjs'

const detect = (root) => JSON.parse(spawnSync(process.execPath, [join(SCRIPTS, 'detect.mjs'), '--root', root], { encoding: 'utf8' }).stdout)
const legacy = scratch('legacy')
after(() => legacy.cleanup())

// The fields detect reported before adopt existed, in order.
const FIELDS = ['root', 'name', 'existingProject', 'framework', 'packageManager', 'typescript', 'styling', 'storyTools', 'playwright', 'monorepo', 'scripts', 'devPort', 'componentDirs', 'nestedPackages', 'styleFiles', 'aliases', 'suggestedConfig']

test('a repo with its own setup: the lane, the extra header keys, its graph, ratchet, token list and DESIGN.md', () => {
  const out = detect(legacy.root)
  assert.deepEqual(Object.keys(out), [...FIELDS, 'adoptable'])
  assert.deepEqual(out.adoptable, [
    { kind: 'lane', paths: ['src/stories'], note: 'a gated story lane with a manifest' },
    { kind: 'headers', paths: [], note: 'ds: keys beyond the built-in ones: theme (3), inputs (2), styles (2), breakpoint (1), owner (1)' },
    { kind: 'graph', paths: ['docs/system/graph.md'], note: 'a generated graph, 4 node headings' },
    { kind: 'ratchet', paths: ['docs/system/ratchet.json'], note: 'a ratchet, 3 rules' },
    { kind: 'tokens', paths: ['docs/system/tokens.json'], note: "the repo's own token file, 3 tokens" },
    { kind: 'design-md', paths: ['DESIGN.md'], note: 'a DESIGN.md' },
  ])
})

// A throwaway repo with these files, removed after `fn` runs.
function repo(files, fn) {
  const root = mkdtempSync(join(tmpdir(), 'massimo-detect-'))
  try {
    for (const [f, body] of Object.entries(files)) {
      mkdirSync(join(root, f, '..'), { recursive: true })
      writeFileSync(join(root, f), body)
    }
    return fn(root)
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
}

const PLAIN = {
  'package.json': '{"dependencies":{"react":"18","vite":"5"}}',
  'src/components/Button.tsx': '// ds:group Primitives / Actions\n// ds:use-when a reader acts\nexport const Button = () => null\n',
  'src/styles/app.css': ':root { --a: 1px; --b: 2px; --c: 3px; --d: 4px; --e: 5px; }\n',
  'docs/notes.md': '# Notes\n\n### One\n### Two\n### Three\n',
}

test('a repo with nothing to adopt gets the report it always got', () => {
  repo(PLAIN, (root) => assert.deepEqual(Object.keys(detect(root)), FIELDS))
})

test('a README that says "generated" and has one-word headings is not a graph, and its neighbours are not notes', () => {
  const files = {
    ...PLAIN,
    'README.md': '# thumbs\n\nA small React library. Thumbnails are generated on demand and cached.\n\n### Installation\n\nnpm install thumbs\n\n### Usage\n\nImport it.\n\n### Options\n\nNone yet.\n',
    'CHANGELOG.md': '# Changelog\n\n## 1.0.0\n\nFirst release.\n',
    'CONTRIBUTING.md': '# Contributing\n\nOpen a pull request.\n',
    // Marked as generated, with one-word headings that name no file with a header.
    'docs/api/index.md': '# API\n\n<!-- Generated by scripts/api.mjs. Do not edit. -->\n\n### Install\n### Usage\n### Options\n',
    'scripts/api.mjs': '// writes docs/api/index.md\n',
  }
  repo(files, (root) => {
    assert.deepEqual(Object.keys(detect(root)), FIELDS)
    const r = spawnSync(process.execPath, [join(SCRIPTS, 'adopt.mjs'), '--json', '--root', root], { encoding: 'utf8' })
    assert.deepEqual(JSON.parse(r.stdout).own.docs, [])
  })
})

test('a design.md is a DESIGN.md only when its front matter has tokens or components', () => {
  const plainDoc = { ...PLAIN, 'docs/design.md': '# Sync service design\n\nHow the sync worker batches writes.\n\n## Queues\n\nOne per tenant.\n' }
  repo(plainDoc, (root) => assert.deepEqual(Object.keys(detect(root)), FIELDS))
  const page = { ...PLAIN, 'docs/design.md': '---\ntitle: Design\n---\n\n## Components\n\n- **Queue**: one per tenant.\n' }
  repo(page, (root) => assert.deepEqual(Object.keys(detect(root)), FIELDS))
  const real = { ...PLAIN, 'docs/design.md': '---\nversion: alpha\ncolors:\n  brand: "#0f766e"\n---\n\n# Brand\n' }
  repo(real, (root) => assert.deepEqual(detect(root).adoptable, [{ kind: 'design-md', paths: ['docs/design.md'], note: 'a DESIGN.md' }]))
})

test("a generated graph's folder holds its notes, but the repo root is never that folder", () => {
  const files = {
    ...PLAIN,
    'src/components/Card.tsx': '// ds:group Components / Cards\nexport const Card = () => null\n',
    'src/components/Badge.tsx': '// ds:group Primitives / Status\nexport const Badge = () => null\n',
    'GRAPH.md': '# Graph\n\n<!-- GENERATED by scripts/graph.mjs. Do not edit by hand. -->\n\n### Button\n### Card\n### Badge\n',
    'README.md': '# Site\n',
    'scripts/graph.mjs': "import { writeFileSync } from 'node:fs'\nwriteFileSync('GRAPH.md', '')\n",
  }
  repo(files, (root) => {
    assert.deepEqual(detect(root).adoptable, [{ kind: 'graph', paths: ['GRAPH.md'], note: 'a generated graph, 3 node headings' }])
    const r = spawnSync(process.execPath, [join(SCRIPTS, 'adopt.mjs'), '--json', '--root', root], { encoding: 'utf8' })
    assert.deepEqual(JSON.parse(r.stdout).own.docs.map((d) => d.path), ['GRAPH.md'])
  })
})

test('a key of its own makes a repo adoptable on its own only from two files on', () => {
  const stray = { ...PLAIN, 'src/components/Card.tsx': '// ds:group Components / Cards\n// ds:bogus x\nexport const Card = () => null\n' }
  repo(stray, (root) => assert.deepEqual(Object.keys(detect(root)), FIELDS))
  const two = { ...stray, 'src/components/Badge.tsx': '// ds:group Primitives / Status\n// ds:bogus y\nexport const Badge = () => null\n' }
  repo(two, (root) => assert.deepEqual(detect(root).adoptable, [{ kind: 'headers', paths: [], note: 'ds: keys beyond the built-in ones: bogus (2)' }]))
})

test('keys the config already gives a role or lists as extra are not reported again', () => {
  const root = legacy.root
  writeFileSync(join(root, 'massimo.config.json'), JSON.stringify({ graph: { keys: { theme: { role: 'scope' }, inputs: 'definitions' }, extraKeys: ['owner'] } }))
  try {
    const headers = detect(root).adoptable.find((a) => a.kind === 'headers')
    assert.equal(headers.note, 'ds: keys beyond the built-in ones: styles (2), breakpoint (1)')
  } finally {
    rmSync(join(root, 'massimo.config.json'))
  }
})
