test('DTCG value types: objects, arrays, numbers and composite dimensions', () => {
  const t = withTokens({
    shadow: {
      $type: 'shadow',
      card: { $value: { color: '#00000033', offsetX: '0px', offsetY: { value: 2, unit: 'px' }, blur: '8px', spread: '0px' } },
    },
    motion: {
      ease: { $type: 'cubicBezier', $value: [0.4, 0, 0.2, 1] },
      fast: { $type: 'duration', $value: '150ms' },
    },
    font: {
      body: { $type: 'fontFamily', $value: ['Inter Tight', 'system-ui'] },
      weight: { bold: { $type: 'fontWeight', $value: 700 } },
    },
    color: { $type: 'color', ink: { $value: { colorSpace: 'srgb', components: [0, 0, 0], alpha: 0.5 } } },
    size: { $type: 'dimension', gap: { $value: { value: 12, unit: 'px' } }, ratio: { $type: 'number', $value: 1.5 } },
  })
  try {
    assert.equal(run('tokens', t, ['build']).status, 0)
    const css = read(t.root, 'src', 'styles', 'tokens.generated.css')
    assert.match(css, /--shadow-card: 0px 2px 8px 0px #00000033;/)
    assert.match(css, /--motion-ease: cubic-bezier\(0\.4, 0, 0\.2, 1\);/)
    assert.match(css, /--font-body: "Inter Tight", system-ui;/)
    assert.match(css, /--font-weight-bold: 700;/)
    assert.match(css, /--color-ink: #00000080;/)
    assert.match(css, /--size-gap: 12px;/)
    const figma = readJson(t.project, 'tokens', 'figma-variables.json')
    const types = Object.fromEntries(figma.collections.flatMap((c) => c.variables).map((v) => [v.name, v.type]))
    assert.deepEqual(types, {
      'motion/fast': 'FLOAT', // 150, in ms
      'font/body': 'STRING',
      'font/weight/bold': 'FLOAT',
      'color/ink': 'COLOR',
      'size/gap': 'FLOAT',
      'size/ratio': 'FLOAT',
    })
    assert.deepEqual(figma.effectStyles.map((s) => s.name), ['shadow/card']) // a shadow is an effect style, not a string
    assert.deepEqual(figma.notMirrored, [{ token: 'motion.ease', type: 'cubicBezier', reason: 'Figma has no cubicBezier variable' }])
  } finally {
    t.cleanup()
  }
})
