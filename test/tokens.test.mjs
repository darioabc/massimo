test('tailwind4, tailwind3, scss, json and ts outputs', () => {
  const tw4 = style('tokens.tailwind.css')
  assert.match(tw4, /@theme inline \{[\s\S]*--color-bg-default: var\(--color-bg-default\);[\s\S]*--spacing-1: var\(--spacing-1\);[\s\S]*--radius-md: var\(--radius-md\);[\s\S]*--font-sans: var\(--font-sans\);[\s\S]*--text-lg: var\(--text-lg\);/)
  assert.ok(!tw4.includes('--touch-target')) // the size group has no Tailwind namespace
  const tw3 = style('tokens.tailwind.cjs')
  assert.ok(tw3.startsWith('// Generated by massimo tokens'))
  const exported = new Function('module', `${tw3}; return module.exports`)({ exports: {} })
  assert.equal(exported.colors.bg.default, 'var(--color-bg-default)')
  assert.equal(exported.colors.neutral['950'], 'var(--color-neutral-950)')
  assert.equal(exported.borderRadius.md, 'var(--radius-md)')
  assert.equal(exported.fontSize.lg, 'var(--text-lg)')
  assert.match(style('_tokens.scss'), /^\$color-bg-default: var\(--color-bg-default\);$/m)
  assert.match(style('_tokens.scss'), /^\$touch-target: var\(--touch-target\);$/m)
  const flat = JSON.parse(style('tokens.flat.json'))
  assert.deepEqual(flat.modes, ['default', 'dark'])
  assert.deepEqual(flat.tokens['color.fg.muted'].values, { default: '#777777', dark: '#9a9a9a' })
  assert.deepEqual(flat.tokens['color.bg.default'].values, { default: '#ffffff', dark: '#0a0a0a' }) // alias chains resolve per mode
  assert.match(style('tokens.ts'), /export const tokens = \{[\s\S]*bg: \{\n {6}default: 'var\(--color-bg-default\)',[\s\S]*\} as const\n$/)
})

test('figma-variables.json: collections, modes, aliases, value types', () => {
  const figma = readJson(ctx.project, 'tokens', 'figma-variables.json')
  assert.equal(figma.generatedBy, 'massimo tokens')
  assert.deepEqual(figma.collections.map((c) => c.name), ['Primitives', 'Semantic'])
  const [primitives, semantic] = figma.collections
  assert.deepEqual(primitives.modes, ['Light']) // no primitive changes in dark, so no Dark mode to fill
  assert.deepEqual(semantic.modes, ['Light', 'Dark'])
  const byName = (c, n) => c.variables.find((v) => v.name === n)
  assert.deepEqual(byName(primitives, 'color/neutral/0'), {
    name: 'color/neutral/0',
    type: 'COLOR',
    scopes: [], // a colour ramp hides once semantic colours exist
    values: { Light: { r: 1, g: 1, b: 1, a: 1 } },
    description: '',
    codeSyntax: { WEB: 'var(--color-neutral-0)' },
  })
  assert.deepEqual(byName(semantic, 'color/bg/default').values, {
    Light: { alias: 'color/neutral/0', collection: 'Primitives' },
    Dark: { alias: 'color/neutral/950', collection: 'Primitives' },
  })
  assert.equal(byName(semantic, 'color/bg/default').description, 'Page background')
  assert.deepEqual(byName(semantic, 'color/bg/default').scopes, ['FRAME_FILL', 'SHAPE_FILL'])
  assert.deepEqual(byName(semantic, 'color/fg/muted').scopes, ['TEXT_FILL'])
  assert.deepEqual(byName(primitives, 'spacing/1').scopes, ['GAP'])
  assert.deepEqual(byName(primitives, 'radius/md').scopes, ['CORNER_RADIUS'])
  assert.deepEqual(byName(primitives, 'text/lg').scopes, ['FONT_SIZE'])
  assert.deepEqual(byName(primitives, 'font/sans').scopes, ['FONT_FAMILY'])
  assert.equal(byName(primitives, 'font/sans').values.Light, 'Geist Sans') // Figma takes one family
  assert.deepEqual(byName(primitives, 'spacing/1').values, { Light: 4 }) // 0.25rem -> 4
  assert.equal(byName(primitives, 'spacing/1').type, 'FLOAT')
  assert.equal(byName(primitives, 'font/sans').type, 'STRING')
  assert.equal(byName(primitives, 'size/touch').values.Light, 44)
})

