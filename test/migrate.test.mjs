// tokens.mjs migrate: the fixture's old tokens.json goes to 2025.10 and back
// with nothing lost and every output unchanged, anything that cannot carry
// over exactly is reported, and golden files pin what 2025.10 looks like.

import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { test } from 'node:test'
import { colorFromCss } from '../scripts/lib/color.mjs'
import { golden, read, readJson, run, scratch, withTokens } from './helpers.mjs'

const tokensDir = (t) => join(t.root, 'design-system', 'tokens')
const OUTPUTS = ['tokens.generated.css', 'tokens.tailwind.css', 'tokens.tailwind.cjs', '_tokens.scss', 'tokens.flat.json', 'tokens.ts']
const body = (text) => text.split('\n').filter((l) => !l.includes('Generated by massimo') && !l.startsWith('/* Source: ')).join('\n')

// Every output, without the line that names its source.
function outputs(t) {
  const out = Object.fromEntries(OUTPUTS.map((f) => [f, body(read(t.root, 'src', 'styles', f))]))
  out['figma-variables.json'] = body(read(t.project, 'tokens', 'figma-variables.json'))
  out['kit.css'] = body(read(t.project, 'kit', 'kit.css'))
  return out
}

test('the fixture migrates to 2025.10 with nothing lost and every output unchanged', () => {
  const t = scratch()
  try {
    assert.equal(run('tokens', t, ['build']).status, 0)
    const before = outputs(t)
    const original = read(tokensDir(t), 'tokens.json')
    const r = run('tokens', t, ['migrate'])
    assert.equal(r.status, 0, r.stderr)
    assert.match(r.stdout, /0 values not carried over exactly, 0 outputs changed/)
    assert.equal(readJson(t.root, 'massimo.config.json').tokens.source, 'design-system/tokens/tokens.resolver.json')
    for (const f of ['tokens.resolver.json', 'base.tokens.json', 'theme/dark.tokens.json']) {
      assert.equal(read(tokensDir(t), f), golden(`fixture-2025.10/${f}`, read(tokensDir(t), f)) ?? read(tokensDir(t), f), f)
    }
    const report = read(tokensDir(t), 'migration-report.md')
    assert.match(report, /Every value carried over exactly\./)
    assert.match(report, /Every output builds the same as before/)
    assert.equal(read(tokensDir(t), 'tokens.json'), original) // the old file is left for the user to remove
    assert.equal(run('tokens', t, ['build']).status, 0)
    assert.deepEqual(outputs(t), before)
    assert.match(run('tokens', t, ['migrate']).stderr, /already in the 2025\.10 format/)
  } finally {
    t.cleanup()
  }
})

test('and back: the old dialect again, every value equal', () => {
  const t = scratch()
  try {
    const original = readJson(tokensDir(t), 'tokens.json')
    assert.equal(run('tokens', t, ['migrate']).status, 0)
    assert.match(run('tokens', t, ['migrate', '--to', 'legacy']).stderr, /these files exist already: design-system\/tokens\/tokens\.json/)
    const r = run('tokens', t, ['migrate', '--to', 'legacy', '--force'])
    assert.equal(r.status, 0, r.stderr)
    assert.match(r.stdout, /0 values not carried over exactly, 0 outputs changed/)
    assert.equal(readJson(t.root, 'massimo.config.json').tokens.source, 'design-system/tokens/tokens.json')
    const back = readJson(tokensDir(t), 'tokens.json')
    // Values come back as CSS text; colours are compared by what they are, not how they are written.
    const flat = (doc, out = {}, path = []) => {
      for (const [k, v] of Object.entries(doc)) {
        if (k.startsWith('$')) continue
        if ('$value' in v) out[[...path, k].join('.')] = { value: v.$value, ext: v.$extensions?.massimo ?? {} }
        else flat(v, out, [...path, k])
      }
      return out
    }
    const same = (a, b) => {
      if (typeof a === 'string' && typeof b === 'string' && colorFromCss(a) && colorFromCss(b)) return colorFromCss(a).hex === colorFromCss(b).hex
      return JSON.stringify(a) === JSON.stringify(b)
    }
    const [x, y] = [flat(original), flat(back)]
    assert.deepEqual(Object.keys(y), Object.keys(x))
    for (const name of Object.keys(x)) {
      assert.ok(same(x[name].value, y[name].value), `${name}: ${JSON.stringify(x[name].value)} vs ${JSON.stringify(y[name].value)}`)
      for (const [mode, v] of Object.entries(x[name].ext.modes ?? {})) assert.ok(same(v, y[name].ext.modes?.[mode]), `${name} ${mode}`)
      assert.equal(y[name].ext.cssVar, x[name].ext.cssVar, name)
      assert.equal(y[name].ext.on, x[name].ext.on, name)
    }
  } finally {
    t.cleanup()
  }
})

test('what cannot carry over exactly is reported, and CSS still builds the same', () => {
  const t = withTokens({
    size: { $type: 'dimension', tight: { $value: '-0.02em' }, fluid: { $value: 'clamp(1rem, 2vw, 2rem)' }, gap: { $value: 12 } },
    motion: { fast: { $value: '150ms' }, ease: { $value: 'ease-out' } },
    other: { grid: { $value: 'repeat(3, 1fr)' } },
  })
  try {
    assert.equal(run('tokens', t, ['build']).status, 0)
    const before = body(read(t.root, 'src', 'styles', 'tokens.generated.css'))
    const r = run('tokens', t, ['migrate'])
    assert.equal(r.status, 0, r.stderr)
    const report = read(tokensDir(t), 'migration-report.md')
    assert.match(report, /`size\.tight` \(approximated\): -0\.02em is relative to the text it sits in, so CSS keeps it; outside CSS it is -0\.32px/)
    assert.match(report, /`size\.fluid` \(css-only\): "clamp\(1rem, 2vw, 2rem\)" is not px or rem, so it has no DTCG dimension; it reaches the CSS outputs as written/)
    assert.match(report, /`motion\.fast` \(typed\): had no type; read as a duration/)
    assert.match(report, /`other\.grid` \(css-only\)/)
    const base = readJson(tokensDir(t), 'base.tokens.json')
    assert.deepEqual(base.size.gap.$value, { value: 12, unit: 'px' })
    assert.deepEqual(base.size.tight, { $value: { value: -0.32, unit: 'px' }, $extensions: { massimo: { css: '-0.02em' } } })
    assert.deepEqual(base.$extensions.massimo.cssOnly['size.fluid'], { css: 'clamp(1rem, 2vw, 2rem)', after: 'size.tight' })
    assert.deepEqual(base.motion.ease, { $type: 'cubicBezier', $value: [0, 0, 0.58, 1] })
    assert.equal(run('tokens', t, ['build']).status, 0)
    const after = body(read(t.root, 'src', 'styles', 'tokens.generated.css'))
    // The ease keyword is now its curve; everything else is as it was.
    assert.deepEqual(after.replace('cubic-bezier(0, 0, 0.58, 1)', 'ease-out'), before)
  } finally {
    t.cleanup()
  }
})

test('migrate refuses while the vendored scripts are older than it', () => {
  const t = scratch()
  try {
    const lib = join(t.project, 'scripts', 'lib')
    mkdirSync(lib, { recursive: true })
    writeFileSync(join(lib, 'project.mjs'), "export const SCRIPTS_VERSION = '0.0.9'\n")
    const r = run('tokens', t, ['migrate'])
    assert.equal(r.status, 1)
    assert.match(r.stderr, /are 0\.0\.9, older than this .*; update them first \(init\.mjs --update-scripts\)/)
  } finally {
    t.cleanup()
  }
})

test('golden: every output built from a 2025.10 set with composites', () => {
  const doc = JSON.parse(read(join(import.meta.dirname ?? new URL('.', import.meta.url).pathname, 'golden', 'composites', 'tokens.json')))
  const t = withTokens(doc)
  try {
    const r = run('tokens', t, ['build'])
    assert.equal(r.status, 0, r.stderr)
    const all = outputs(t)
    for (const [name, text] of Object.entries(all)) assert.equal(text, golden(`composites/${name}`, text) ?? text, name)
  } finally {
    t.cleanup()
  }
})
